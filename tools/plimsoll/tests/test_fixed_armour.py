class DeclarationTests(unittest.TestCase):

    def test_absent_and_null_are_disabled_and_return_an_empty_list(self):
        self.assertEqual(fa.validate_configs(None), [])
        self.assertEqual(fa.validate_configs([]), [])

    def test_a_non_array_section_is_refused(self):
        for raw in ({"id": "x"}, "belt_main", 3):
            with self.assertRaises(fa.ArmourValidationError):
                fa.validate_configs(raw)

    def test_more_than_fifty_records_are_refused(self):
        raw = [{"id": "region%d" % index, "kind": "bulge"} for index in range(51)]
        with self.assertRaises(fa.ArmourValidationError) as error:
            fa.validate_configs(raw)
        self.assertIn("at most 50", str(error.exception))

    def test_fifty_records_are_accepted(self):
        raw = [{"id": "region%d" % index, "kind": "bulge"} for index in range(50)]
        self.assertEqual(len(fa.validate_configs(raw)), 50)

    def test_a_wrong_id_is_refused(self):
        for identity in ("", "a b", "x" * 81, 7, "bad/slash"):
            with self.assertRaises(fa.ArmourValidationError):
                fa.validate_configs([{"id": identity, "kind": "bulge"}])

    def test_a_duplicate_id_is_refused(self):
        with self.assertRaises(fa.ArmourValidationError):
            fa.validate_configs([{"id": "same", "kind": "bulge"},
                                 {"id": "same", "kind": "bulkhead"}])

    def test_an_unknown_kind_is_refused(self):
        with self.assertRaises(fa.ArmourValidationError):
            fa.validate_configs([{"id": "x", "kind": "rotating_armour"}])

    def test_an_unknown_common_field_is_refused(self):
        with self.assertRaises(fa.ArmourValidationError):
            fa.validate_configs([{"id": "x", "kind": "bulge", "angle_deg": 20.0}])

    def test_a_field_that_does_not_belong_to_the_chosen_kind_is_refused(self):
        # A conning tower has no plan extent, and a belt has no deck selector.
        with self.assertRaises(fa.ArmourValidationError):
            fa.validate_configs([{"id": "x", "kind": "conning", "height_m": 4.0}])
        with self.assertRaises(fa.ArmourValidationError):
            fa.validate_configs([{"id": "x", "kind": "bulkhead", "coverage_index": 2}])

    def test_a_blank_provenance_note_is_absent_and_never_a_claim(self):
        # A normal editor writes an empty note for a record it has not annotated.
        # That is a legitimate draft state, not a reason to refuse the project.
        records = fa.validate_configs([{"id": "draft", "kind": "bulge", "source": "   "}])
        self.assertIsNone(records[0]["source"])
        self.assertIsNone(fa.validate_configs([{"id": "d", "kind": "bulge"}])[0]["source"])
        with self.assertRaises(fa.ArmourValidationError):
            fa.validate_configs([{"id": "draft", "kind": "bulge", "source": 7}])

    def test_a_blank_binding_names_nothing_and_is_refused(self):
        for field in ("system_id", "item_id"):
            with self.subTest(field=field):
                with self.assertRaises(fa.ArmourValidationError):
                    fa.validate_configs([{"id": "x", "kind": "bulge", field: ""}])

    def test_an_unclassified_draft_may_carry_any_engineering_field(self):
        records = fa.validate_configs([{"id": "draft", "kind": None, "thickness_mm": 100.0,
                                        "coverage_index": 3}])
        self.assertEqual(records[0]["kind"], None)
        self.assertEqual(records[0]["thickness_mm"], 100.0)

    def test_a_wrong_type_a_nonfinite_number_and_a_negative_are_refused(self):
        for extra in ({"thickness_mm": "6"}, {"thickness_mm": True},
                      {"thickness_mm": float("nan")}, {"thickness_mm": float("inf")},
                      {"length_m": -1.0}, {"height_m": -0.5},
                      {"coverage_index": 2.5}, {"coverage_index": "2"}):
            with self.assertRaises(fa.ArmourValidationError):
                fa.validate_configs([dict({"id": "x", "kind": "deck"}, **extra)])

    def test_the_declared_bounds_are_inclusive_at_both_ends(self):
        fa.validate_configs([{"id": "x", "kind": "bulkhead", "thickness_mm": 0.0,
                              "length_m": 5000.0, "height_m": 100.0}])
        for extra in ({"thickness_mm": 2000.001}, {"length_m": 5000.001}, {"height_m": 100.001}):
            with self.assertRaises(fa.ArmourValidationError):
                fa.validate_configs([dict({"id": "x", "kind": "bulkhead"}, **extra)])

    def test_a_fractional_selector_is_refused_rather_than_truncated(self):
        with self.assertRaises(fa.ArmourValidationError) as error:
            fa.validate_configs([{"id": "x", "kind": "deck", "coverage_index": 4.5}])
        self.assertIn("integer", str(error.exception))

    def test_the_seven_deck_selectors_are_exactly_zero_to_six(self):
        fa.validate_configs([{"id": "x", "kind": "deck", "coverage_index": 6}])
        with self.assertRaises(fa.ArmourValidationError):
            fa.validate_configs([{"id": "x", "kind": "deck", "coverage_index": 7}])

    def test_known_deck_fractions_may_not_exceed_one_together(self):
        fa.validate_configs([{"id": "x", "kind": "deck", "coverage_index": 0,
                              "forecastle_fraction": 0.6, "quarterdeck_fraction": 0.4}])
        with self.assertRaises(fa.ArmourValidationError):
            fa.validate_configs([{"id": "x", "kind": "deck", "coverage_index": 0,
                                  "forecastle_fraction": 0.7, "quarterdeck_fraction": 0.4}])

    def test_one_known_fraction_alone_is_never_clamped_or_completed(self):
        records = fa.validate_configs([{"id": "x", "kind": "deck", "coverage_index": 0,
                                        "forecastle_fraction": 0.26}])
        self.assertEqual(records[0]["forecastle_fraction"], 0.26)
        self.assertIsNone(records[0]["quarterdeck_fraction"])

    def test_every_field_and_binding_may_be_null_in_a_saved_draft(self):
        records = fa.validate_configs([{"id": "draft", "kind": "bulge"}])
        self.assertEqual(records[0]["system_id"], None)
        self.assertEqual(records[0]["item_id"], None)
        self.assertEqual(records[0]["thickness_mm"], None)
        self.assertIs(fa.evaluate(records[0], CONTEXT)["status"], "unavailable")
        self.assertIs(fa.evaluate(records[0], {})["status"], "unavailable")


