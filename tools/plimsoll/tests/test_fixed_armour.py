class MethodIdentityTests(unittest.TestCase):

    def test_the_kernel_carries_its_own_method_and_source_identity(self):
        self.assertEqual(fa.METHOD_VERSION, "sps-3b3-fixed-armour-v1")
        self.assertEqual(fa.SOURCE_ASSEMBLY, "SpringSharpMono 3.0.3032.29945")
        self.assertEqual(fa.SOURCE_SHA256,
                         "82ecc3fedf76af222dd13ad68258f3ae92146e9fad7dc6a4a96f3270fccf71fc")
        for constant in ("SOURCE_LOCATION", "SOURCE_SCOPE"):
            self.assertIsInstance(getattr(fa, constant), str)
            self.assertTrue(getattr(fa, constant))
        self.assertEqual(len(fa.SOURCE_SHA256), 64)

    def test_the_empirical_mass_constant_is_the_recovered_one(self):
        self.assertEqual(fa.EMPIRICAL_MASS_CONSTANT, INCH_CONSTANT)
        self.assertEqual(fa.MM_PER_INCH, 25.4)
        self.assertEqual(fa.M_PER_FT, 0.3048)

    def test_exactly_seven_kinds_map_to_exactly_seven_roles(self):
        self.assertEqual(len(fa.KINDS), 7)
        self.assertEqual(sorted(fa.ROLE_BY_KIND), sorted(fa.KINDS))
        self.assertEqual(len(set(fa.ROLE_BY_KIND.values())), 7)
        self.assertEqual(fa.ROLE_BY_KIND["conning"], "conning")
        self.assertEqual(fa.ROLE_BY_KIND["bulge"], "armour_bulge")
        self.assertEqual(len(fa.DECK_SELECTOR_NAMES), 7)

    def test_the_result_shape_is_the_documented_contract(self):
        result = reading(thickness_mm=152.4, length_m=91.44, height_m=6.096)
        self.assertEqual(sorted(result), ["diagnostics", "id", "kind", "method_version",
                                          "origin", "provenance", "status", "values"])
        self.assertEqual(result["id"], "region")
        self.assertEqual(result["kind"], "belt_main")
        self.assertEqual(result["method_version"], fa.METHOD_VERSION)
        self.assertEqual(result["status"], "available")
        self.assertIn("total_long_tons", result["values"])
        self.assertIn("mass_t", result["values"])
        for key in ("kernel", "source_location", "source_sha256", "formula", "inputs",
                    "assumptions", "context"):
            self.assertIn(key, result["provenance"]), key


