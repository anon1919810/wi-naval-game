class VerificationSourceIdentityTests(unittest.TestCase):
    """Both new kernels must appear in the identity the verification report signs.

    The mechanism has two parts and both are checked here: ``files`` hashes every
    module in the package by glob, so a new kernel is measured without any change
    to the numerical verification, and ``method_versions`` is an explicit list of
    versioned kernels, so a new one has to be named there to be identifiable. No
    existing method identity is dropped to make room for either.
    """

    @classmethod
    def setUpClass(cls):
        # The verifier is a package module with relative imports, so it is reached
        # through the package rather than through the flat path this suite uses
        # for the pure kernels.
        root = PKG.parent
        if str(root) not in sys.path:
            sys.path.insert(0, str(root))
        from plimsoll import verification
        cls.identity = verification._source_identity()

    def test_both_kernel_sources_are_hashed_by_the_package_glob(self):
        measured = {entry["module"]: entry for entry in self.identity["files"]}
        for module, name in (("plimsoll.fixed_armour", "fixed_armour.py"),
                             ("plimsoll.concept_cost", "concept_cost.py")):
            self.assertIn(module, measured)
            self.assertEqual(len(measured[module]["sha256"]), 64)
            self.assertEqual(Path(measured[module]["path"]).name, name)

    def test_both_kernel_method_versions_are_named_in_the_identity(self):
        versions = self.identity["method_versions"]
        self.assertEqual(versions["plimsoll.fixed_armour"], fa.METHOD_VERSION)
        self.assertEqual(versions["plimsoll.concept_cost"], cost.METHOD_VERSION)
        self.assertEqual(versions["plimsoll.verification"], "offline-core-verification-1")

    def test_every_older_method_version_is_retained(self):
        versions = self.identity["method_versions"]
        for name in ("plimsoll.stability", "plimsoll.geometry_analysis",
                     "plimsoll.small_angle_stability", "plimsoll.tank_geometry",
                     "plimsoll.flooding", "plimsoll._flooding_kernel",
                     "plimsoll.verification_oracles", "plimsoll.battery_armour",
                     "plimsoll.battery_layout", "plimsoll.verification"):
            with self.subTest(module=name):
                self.assertIn(name, versions)


class OriginalAssemblyVectorTests(unittest.TestCase):
    """Every recovered fixed-armour reading, against the original assembly itself.

    Unlike everything else in this file, no row here was transcribed from the
    recovered C#. Each one was produced by invoking the original
    ``ArmourControl`` method directly on the recovered binary; the curated
    fixture records only the inputs it received, the number it returned, and the
    binary and method identity it came from. No original code is reproduced.

    The original's own intermediates are ``float``; this module is ``float64``.
    The stated tolerance of the comparison is the fixture's ``relative_tolerance``.
    """

    def test_the_fixture_carries_the_binary_and_method_provenance(self):
        original = VECTORS["original_binary"]
        self.assertEqual(original["sha256"], fa.SOURCE_SHA256)
        self.assertTrue(original["sha256_matches"])
        self.assertIn("SpringSharpMono", original["assembly"])
        self.assertEqual(VECTORS["method_identities"]["fixed_armour"], fa.METHOD_VERSION)
        self.assertEqual(VECTORS["original_convention"]["mass"], "long tons (2240 lb)")
        # The fixture is evidence only: it names the recovered locations and the
        # binary, and it carries no recovered code.
        self.assertTrue(VECTORS["recovered_source"])
        for row in ARMOUR_ROWS:
            self.assertTrue(row["method"].startswith("ArmourControl."))
            self.assertTrue(row["source_location"].startswith("ArmourControl.cs:"))

    def test_the_fixture_covers_every_kind_and_every_coverage_selector(self):
        self.assertEqual(len(ARMOUR_ROWS), VECTORS["coverage"]["armour_valid_cases"])
        self.assertEqual(sorted({row["kind"] for row in ARMOUR_ROWS}), sorted(fa.KINDS))
        self.assertEqual(VECTORS["coverage"]["deck_selectors_covered"], list(range(7)))

    def test_every_original_fixed_armour_reading_is_reproduced(self):
        tolerance = VECTORS["relative_tolerance"]
        worst, worst_id = 0.0, None
        for row in ARMOUR_ROWS:
            result = fa.evaluate(dict(row["in"], id=row["id"], kind=row["kind"]), row["ctx"])
            actual = result["values"]["total_long_tons"]
            self.assertIsNotNone(actual, "%s: %s" % (row["id"], result["diagnostics"]))
            relative = abs(actual - row["long_tons"]) / max(abs(row["long_tons"]), 1e-9)
            if relative > worst:
                worst, worst_id = relative, row["id"]
            self.assertLessEqual(relative, tolerance, row["id"])
        self.assertIsNotNone(worst_id)

    def test_the_five_coverage_families_stay_separate_numbers(self):
        families = {}
        for row in ARMOUR_ROWS:
            families.setdefault(row["family"], set()).add(row["long_tons"])
        for family, values in families.items():
            self.assertTrue(values, family)
        self.assertEqual(len(families), 8)

    def test_every_coverage_selector_keeps_its_fore_and_quarter_readings(self):
        rows = [row for row in ARMOUR_ROWS
                if row["kind"] == "deck" and row["in"]["coverage_index"] in (4, 5, 6)
                and row["in"]["forecastle_fraction"] > 0
                and row["in"]["quarterdeck_fraction"] > 0
                and row["in"]["thickness_mm"] > 0
                and row["in"]["forecastle_mm"] > 0
                and row["in"]["quarterdeck_mm"] > 0]
        self.assertEqual({row["in"]["coverage_index"] for row in rows}, {4, 5, 6})
        for row in rows:
            result = fa.evaluate(dict(row["in"], id=row["id"], kind="deck"), row["ctx"])
            values = result["values"]
            with self.subTest(case=row["id"]):
                self.assertEqual(result["status"], "available")
                self.assertGreater(values["fore_long_tons"], 0.0)
                self.assertGreater(values["quarter_long_tons"], 0.0)
                self.assertTrue(close(values["total_long_tons"],
                                      values["central_long_tons"] + values["fore_long_tons"]
                                      + values["quarter_long_tons"], 1e-9))

    def test_a_declared_zero_fraction_is_still_a_zero_area_in_the_original_domain(self):
        rows = [row for row in ARMOUR_ROWS
                if row["kind"] == "deck" and row["in"]["forecastle_fraction"] == 0.0
                and row["in"]["quarterdeck_fraction"] == 0.0
                and row["in"]["thickness_mm"] > 0]
        self.assertTrue(rows)
        for row in rows:
            result = fa.evaluate(dict(row["in"], id=row["id"], kind="deck"), row["ctx"])
            with self.subTest(case=row["id"]):
                self.assertEqual(result["values"]["fore_area_sqft"], 0.0)
                self.assertEqual(result["values"]["quarter_area_sqft"], 0.0)
                self.assertEqual(result["values"]["fore_long_tons"], 0.0)
                # A determined zero upper plate still matches the original.
                self.assertTrue(close(result["values"]["total_long_tons"],
                                      row["long_tons"],
                                      VECTORS["relative_tolerance"]))

    def test_the_recorded_unsupported_boundaries_stay_out_of_the_valid_domain(self):
        for row in VECTORS["unsupported_boundary"]["armour"]:
            with self.subTest(case=row["id"]):
                self.assertTrue(row["boundary_note"])
                self.assertNotIn(row["id"], {entry["id"] for entry in ARMOUR_ROWS})


