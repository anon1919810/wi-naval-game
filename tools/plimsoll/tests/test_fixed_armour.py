class PlateReadingTests(unittest.TestCase):

    def test_the_end_belt_bulkhead_and_bulge_are_the_recovered_doubled_plate(self):
        for kind in ("belt_ends", "bulkhead", "bulge"):
            with self.subTest(kind=kind):
                result = reading(kind=kind, thickness_mm=76.2, length_m=30.48, height_m=3.658)
                self.assertEqual(result["status"], "available")
                self.assertTrue(close(result["values"]["total_long_tons"],
                                      reference_plate(30.48, 3.658, 76.2)))
                self.assertTrue(close(result["values"]["area_sqft"],
                                      2.0 * _ft(30.48) * _ft(3.658)))
                self.assertEqual(fa.component_breakdown(result["values"], kind),
                                 {"plate_long_tons": result["values"]["total_long_tons"]})

    def test_a_simple_plate_needs_no_hull_context_at_all(self):
        result = fa.evaluate(
            record(kind="bulkhead", thickness_mm=76.2, length_m=30.48, height_m=3.658), {})
        self.assertEqual(result["status"], "available")
        self.assertTrue(close(result["values"]["total_long_tons"],
                              reference_plate(30.48, 3.658, 76.2)))
        for field in ("length_m", "beam_m", "co_waterplane", "displacement_t"):
            self.assertIsNone(result["provenance"]["context"][field])

    def test_a_declared_zero_thickness_is_a_determined_zero_not_a_missing_number(self):
        for kind, extra in (("bulkhead", {"length_m": 30.0, "height_m": 4.0}),
                            ("belt_main", {"length_m": 30.0, "height_m": 4.0}),
                            ("conning", {"aft_mm": 0.0}),
                            ("deck", {"coverage_index": 0, "forecastle_mm": 0.0,
                                      "quarterdeck_mm": 0.0})):
            with self.subTest(kind=kind):
                result = fa.evaluate(record(kind=kind, thickness_mm=0.0, **extra), {})
                self.assertEqual(result["status"], "available")
                self.assertEqual(result["values"]["total_long_tons"], 0.0)
                self.assertEqual(result["values"]["mass_t"], 0.0)

    def test_one_known_zero_conning_plate_is_not_a_known_zero_tower(self):
        result = fa.evaluate(record(kind="conning", thickness_mm=0.0, aft_mm=101.6), {})
        self.assertEqual(result["status"], "unavailable")

    def test_an_unknown_thickness_is_unknown_and_never_read_as_zero(self):
        result = fa.evaluate(record(kind="bulkhead", length_m=30.0, height_m=4.0), CONTEXT)
        self.assertEqual(result["status"], "unavailable")
        self.assertIsNone(result["values"]["total_long_tons"])
        self.assertTrue(any("not read as a zero thickness" in d["message"]
                            for d in result["diagnostics"]))

    def test_an_unknown_extent_is_unknown_and_never_read_as_zero(self):
        result = fa.evaluate(record(kind="bulkhead", thickness_mm=76.2, height_m=4.0),
                             CONTEXT)
        self.assertEqual(result["status"], "unavailable")
        self.assertTrue(any(d["field"] == "length_m" for d in result["diagnostics"]))


class BeltReadingTests(unittest.TestCase):

    def test_the_main_and_upper_belts_keep_the_recovered_taper(self):
        for kind in ("belt_main", "belt_upper"):
            with self.subTest(kind=kind):
                result = reading(kind=kind, thickness_mm=152.4, length_m=91.44, height_m=6.096)
                self.assertEqual(result["status"], "available")
                self.assertTrue(close(result["values"]["total_long_tons"],
                                      reference_belt(91.44, 6.096, 152.4)))
                self.assertTrue(close(result["values"]["taper_factor"],
                                      ((HULL_LENGTH_FT - _ft(91.44)) / HULL_LENGTH_FT)
                                      ** (1.0 - CO_WATERPLANE)))

    def test_a_belt_longer_than_the_hull_is_unavailable_rather_than_nan(self):
        result = reading(kind="belt_main", thickness_mm=152.4, length_m=200.0, height_m=6.096)
        self.assertEqual(result["status"], "unavailable")
        self.assertIsNone(result["values"]["total_long_tons"])
        self.assertTrue(any("negative base to a fractional power" in d["message"]
                            for d in result["diagnostics"]))

    def test_a_belt_needs_the_hull_length_beam_and_waterplane_coefficient(self):
        for field in ("length_m", "beam_m", "co_waterplane"):
            with self.subTest(missing=field):
                context = dict(CONTEXT)
                del context[field]
                result = fa.evaluate(
                    record(kind="belt_main", thickness_mm=152.4, length_m=91.44,
                           height_m=6.096), context)
                self.assertEqual(result["status"], "unavailable")
                self.assertIsNone(result["values"]["total_long_tons"])

    def test_no_inclination_multiplier_is_invented(self):
        result = reading(kind="belt_main", thickness_mm=152.4, length_m=91.44, height_m=6.096)
        # The recovered expression carries no inclination term at all, so the same
        # declaration must give the same mass whatever inclination a reader types.
        self.assertNotIn("inclination", json.dumps(result["values"]))
        self.assertTrue(close(result["values"]["total_long_tons"],
                              reference_belt(91.44, 6.096, 152.4)))


class DeckReadingTests(unittest.TestCase):

    def _deck(self, selector, **overrides):
        declared = {"kind": "deck", "thickness_mm": 50.8, "coverage_index": selector,
                    "forecastle_fraction": 0.26, "quarterdeck_fraction": 0.20,
                    "forecastle_mm": 50.8, "quarterdeck_mm": 25.4}
        declared.update(overrides)
        return reading(**declared)

    def test_all_seven_recovered_coverage_selectors_are_evaluated(self):
        for selector in range(7):
            with self.subTest(selector=selector):
                result = self._deck(selector)
                self.assertEqual(result["status"], "available")
                self.assertTrue(close(result["values"]["total_long_tons"],
                                      reference_deck(selector, 50.8, 50.8, 25.4, 0.26, 0.20)))
                self.assertEqual(result["values"]["coverage_index"], selector)
                breakdown = fa.component_breakdown(result["values"], "deck")
                self.assertEqual(sorted(breakdown), ["central_long_tons", "fore_long_tons",
                                                     "quarter_long_tons"])
                self.assertAlmostEqual(sum(breakdown.values()),
                                       result["values"]["total_long_tons"], places=9)

    def test_the_four_area_selectors_fall_through_to_one_recovered_central_area(self):
        # ArmourControl.cs:698-703 puts cases 0, 1, 2 and 3 in one branch, so the
        # four labels legitimately read the same recovered central area. They stay
        # four distinct declared choices; the kernel does not invent a difference.
        masses = [self._deck(selector)["values"]["total_long_tons"] for selector in range(4)]
        areas = [self._deck(selector)["values"]["central_area_sqft"] for selector in range(4)]
        for selector, mass in enumerate(masses):
            self.assertEqual(mass, masses[0], selector)
            self.assertEqual(areas[selector], areas[0], selector)
            self.assertAlmostEqual(mass, reference_deck(selector, 50.8, 50.8, 25.4, 0.26, 0.20),
                                   places=9)
        self.assertEqual(len(fa.DECK_SELECTOR_NAMES), 7)

    def test_the_four_box_selectors_are_not_one_number(self):
        masses = [self._deck(selector)["values"]["total_long_tons"] for selector in (4, 5, 6)]
        self.assertEqual(len(set(masses)), 3)
        self.assertNotAlmostEqual(masses[0], masses[2], places=6)

    def test_the_combined_box_is_not_the_sum_of_the_two_single_boxes(self):
        machinery = self._deck(4)["values"]["central_area_sqft"]
        magazines = self._deck(5)["values"]["central_area_sqft"]
        both = self._deck(6)["values"]["central_area_sqft"]
        self.assertNotAlmostEqual(both, machinery + magazines, places=3)
        self.assertGreater(both, machinery)

    def test_a_known_zero_selected_mass_keeps_the_recovered_box_margin(self):
        context = dict(CONTEXT, machinery_mass_t=0.0)
        result = fa.evaluate(
            record(kind="deck", thickness_mm=50.8, coverage_index=4,
                   forecastle_fraction=0.26, quarterdeck_fraction=0.20,
                   forecastle_mm=50.8, quarterdeck_mm=25.4), context)
        self.assertEqual(result["status"], "available")
        # The recovered box keeps its own margin: (0 + 16) * (beam + 16) - 256.
        margin = 16.0 * (HULL_BEAM_FT + 16.0) - 256.0
        self.assertTrue(close(result["values"]["central_area_sqft"], margin))
        self.assertGreater(margin, 0.0)
        self.assertTrue(close(result["values"]["total_long_tons"],
                              reference_deck(4, 50.8, 50.8, 25.4, 0.26, 0.20,
                                             machinery_t=0.0)))

    def test_an_unknown_selected_mass_is_not_that_zero(self):
        context = dict(CONTEXT, machinery_mass_t=None)
        result = fa.evaluate(
            record(kind="deck", thickness_mm=50.8, coverage_index=4,
                   forecastle_fraction=0.26, quarterdeck_fraction=0.20,
                   forecastle_mm=50.8, quarterdeck_mm=25.4), context)
        self.assertEqual(result["status"], "unavailable")
        self.assertIsNone(result["values"]["central_area_sqft"])
        self.assertTrue(any("never read as a zero" in d["message"] for d in result["diagnostics"]))

    def test_a_known_zero_fraction_is_a_determined_zero_area(self):
        result = self._deck(0, forecastle_fraction=0.0, forecastle_mm=None)
        self.assertEqual(result["status"], "available")
        self.assertEqual(result["values"]["fore_area_sqft"], 0.0)
        self.assertEqual(result["values"]["fore_long_tons"], 0.0)

    def test_an_unknown_fraction_is_not_a_zero_fraction(self):
        result = self._deck(0, forecastle_fraction=None)
        self.assertEqual(result["status"], "unavailable")
        self.assertIsNone(result["values"]["total_long_tons"])

    def test_a_missing_fore_or_quarter_layer_stays_unknown(self):
        for field in ("forecastle_mm", "quarterdeck_mm"):
            with self.subTest(missing=field):
                result = self._deck(0, **{field: None})
                self.assertEqual(result["status"], "unavailable")
