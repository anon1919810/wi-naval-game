# MainForm.cs:22, the recovered empirical mass constant, re-transcribed here so
# the tests never import it from the module under test.
INCH_CONSTANT = 0.0185
FEET_PER_METRE = 1.0 / 0.3048
INCHES_PER_MM = 1.0 / 25.4
LONG_TON_KG = 1016.0469088
SQFT_PER_SQM = (1.0 / 0.3048) ** 2

# One synthetic hull in canonical units. Its waterplane area is the recovered
# ``co_waterplane x length x beam``, converted from square feet to square metres,
# which is exactly what the deck expression reads.
HULL_LENGTH_M = 152.4
HULL_BEAM_M = 18.288
CO_WATERPLANE = 0.72
DISPLACEMENT_T = 8200.0
MACHINERY_T = 1168.4539
AMMUNITION_T = 45.7221
HULL_LENGTH_FT = HULL_LENGTH_M * FEET_PER_METRE
HULL_BEAM_FT = HULL_BEAM_M * FEET_PER_METRE
WATERPLANE_SQFT = CO_WATERPLANE * HULL_LENGTH_FT * HULL_BEAM_FT
WATERPLANE_M2 = WATERPLANE_SQFT / SQFT_PER_SQM
CONTEXT = {
    "length_m": HULL_LENGTH_M,
    "beam_m": HULL_BEAM_M,
    "co_waterplane": CO_WATERPLANE,
    "waterplane_area_m2": WATERPLANE_M2,
    "displacement_t": DISPLACEMENT_T,
    "machinery_mass_t": MACHINERY_T,
    "ammunition_mass_t": AMMUNITION_T,
}


def _ft(metres):
    return metres * FEET_PER_METRE


def _inches(millimetres):
    return millimetres * INCHES_PER_MM


def _lt(tonnes):
    return tonnes * 1000.0 / LONG_TON_KG


# ArmourControl.cs:602-608 and :620-626, transcribed verbatim.
def reference_belt(length_m, height_m, thickness_mm):
    length_ft = _ft(length_m)
    taper = ((HULL_LENGTH_FT - length_ft) / HULL_LENGTH_FT) ** (1.0 - CO_WATERPLANE)
    return (length_ft + taper * HULL_BEAM_FT) * _ft(height_m) * _inches(thickness_mm) \
        * INCH_CONSTANT * 2.0


# ArmourControl.cs:610-618, :654-669 and :671-686, transcribed verbatim.
def reference_plate(length_m, height_m, thickness_mm):
    return 2.0 * _ft(length_m) * _ft(height_m) * _inches(thickness_mm) * INCH_CONSTANT


# ArmourControl.cs:694-725, transcribed verbatim including the four-way
# waterplane branch, the three-way recovered box branch, and the two plate terms
# the recovered method adds AFTER the switch for every selector.
def reference_deck(selector, central_mm, fore_mm, quarter_mm, forecastle, quarterdeck,
                   displacement_t=DISPLACEMENT_T, machinery_t=MACHINERY_T,
                   ammunition_t=AMMUNITION_T):
    length_ft, beam_ft = HULL_LENGTH_FT, HULL_BEAM_FT
    fore = ((2.0 * forecastle) ** (1.0 - CO_WATERPLANE ** 2) * beam_ft * length_ft
            * forecastle / 2.0)
    quarter = (quarterdeck ** (1.0 - CO_WATERPLANE) * beam_ft * length_ft
               * quarterdeck / 4.0
               + (quarterdeck ** (1.0 - CO_WATERPLANE)
                  + (2.0 * quarterdeck) ** (1.0 - CO_WATERPLANE))
               * beam_ft * length_ft * quarterdeck / 4.0)
    if selector in (0, 1, 2, 3):
        central = (WATERPLANE_SQFT - fore - quarter) * 1.01
    else:
        loads = 0.0
        if selector in (4, 6):
            loads += 3.0 * _lt(machinery_t)
        if selector in (5, 6):
            loads += _lt(ammunition_t)
        central = ((loads / (_lt(displacement_t) * 0.94) * 0.65 * length_ft + 16.0)
                   * (beam_ft + 16.0) - 256.0)
    return ((central * _inches(central_mm) + fore * _inches(fore_mm)
             + quarter * _inches(quarter_mm)) * INCH_CONSTANT)


# ArmourControl.cs:727-735, transcribed verbatim.
def reference_conning(fore_mm, aft_mm):
    scale = 10.0 * (_lt(DISPLACEMENT_T) / 10000.0) ** (2.0 / 3.0)
    return scale * (_inches(fore_mm) + _inches(aft_mm))


def record(**overrides):
    declared = {"id": "region", "kind": "belt_main", "system_id": "armour.fixed",
                "item_id": "armour.fixed.belt_main", "source": "synthetic declaration"}
    declared.update(overrides)
    return fa.validate_configs([declared])[0]


def reading(**overrides):
    context = dict(CONTEXT)
    context.update(overrides.pop("context", {}))
    return fa.evaluate(record(**overrides), context)


def close(actual, expected, tolerance=1e-12):
    if expected == 0:
        return abs(actual) <= tolerance
    return abs(actual - expected) <= tolerance * abs(expected)


