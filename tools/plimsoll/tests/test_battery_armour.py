class VerificationSourceIdentityTests(unittest.TestCase):
    """The kernel must appear in the identity the verification report signs.

    The mechanism has two parts and both are checked here: ``files`` hashes every
    module in the package by glob, so the new kernel is measured without any
    change to the numerical verification, and ``method_versions`` is an explicit
    list of versioned kernels, so the new one has to be named there to be
    identifiable. No existing method identity may be dropped to make room.
    """

    @classmethod
    def setUpClass(cls):
        # The verifier is a package module with relative imports, so it is
        # reached through the package rather than through the flat path this
        # suite uses for the pure kernels.
        root = PKG.parent
        if str(root) not in sys.path:
            sys.path.insert(0, str(root))
        from plimsoll import verification
        cls.identity = verification._source_identity()

    def test_the_kernel_source_is_hashed_by_the_package_glob(self):
        measured = {entry["module"]: entry for entry in self.identity["files"]}
        self.assertIn("plimsoll.battery_armour", measured)
        entry = measured["plimsoll.battery_armour"]
        self.assertEqual(len(entry["sha256"]), 64)
        self.assertEqual(Path(entry["path"]).name, "battery_armour.py")

    def test_the_kernel_method_version_is_named_in_the_identity(self):
        versions = self.identity["method_versions"]
        self.assertEqual(versions["plimsoll.battery_armour"], ba.METHOD_VERSION)
        self.assertEqual(versions["plimsoll.verification"], "offline-core-verification-1")

    def test_every_older_method_version_is_retained(self):
        versions = self.identity["method_versions"]
        for name in ("plimsoll.stability", "plimsoll.geometry_analysis",
                     "plimsoll.small_angle_stability", "plimsoll.tank_geometry",
                     "plimsoll.flooding", "plimsoll._flooding_kernel",
                     "plimsoll.verification_oracles", "plimsoll.verification"):
            with self.subTest(module=name):
                self.assertIn(name, versions)


class OriginalAssemblyAnchorTests(unittest.TestCase):
    """One vector produced by RUNNING the original assembly.

    Unlike everything else in this file, this row was not transcribed from the
    recovered C#. The accepting reviewer drove the original
    ``GunControl.armWeightCalc`` on an isolated uninitialised control and
    reported the result in
    ``outputs/Plimsoll-battery-armour-2026-10-15/review1-original-comparison.json``
    (416 cases, 2496 outputs, assembly SHA256
    ``82ecc3fe...f71fc``). It is recorded here with that provenance and with no
    claim beyond the single case below.

    It is kept as a regression anchor because it is what caught the one real
    defect in this kernel: the recovered ``freeGun`` is FEET, so feeding declared
    metres straight into the expression returned 0.3048 of the original.
    """

    ANCHOR = dict(calibre_mm=304.8, year=1910, gun_type="muzzle_loading",
                  mount_type="open_barbette", mount_count=4, barrels_per_mount=1,
                  shared_cradle=False, face_mm=254.0, rear_roof_mm=127.0,
                  barbette_mm=101.6, freeboard_m=8.0, super_factor=1.0)
    BARBETTE = 497.276581
    TOTAL = 594.1058

    def test_the_barbette_mass_matches_the_original_assembly(self):
        values = ba.estimate(**self.ANCHOR)["values"]
        self.assertLessEqual(relative(values["barbette_long_tons"], self.BARBETTE), 1e-5)

    def test_the_total_matches_the_original_assembly(self):
        values = ba.estimate(**self.ANCHOR)["values"]
        self.assertLessEqual(relative(values["total_long_tons"], self.TOTAL), 1e-5)

    def test_the_anchor_is_the_known_barbette_unit_boundary(self):
        # The recovered expression reads FEET. Declared metres are converted once
        # and the conversion is linear in the freeboard, so a metres-fed
        # barbette would be exactly 0.3048 of this anchor's original value.
        values = ba.estimate(**self.ANCHOR)["values"]
        self.assertAlmostEqual(values["freeboard_ft"], 8.0 / 0.3048, places=12)
        halved = ba.estimate(**dict(self.ANCHOR, freeboard_m=4.0))["values"]
        self.assertAlmostEqual(halved["barbette_long_tons"],
                               values["barbette_long_tons"] / 2.0, places=9)
        self.assertAlmostEqual(values["barbette_long_tons"], self.BARBETTE,
                               delta=self.BARBETTE * 1e-5)
        self.assertNotAlmostEqual(values["barbette_long_tons"] * 0.3048, self.BARBETTE,
                                  delta=self.BARBETTE * 1e-5)

    def test_the_anchor_declares_the_barbette_as_a_fixed_structure(self):
        # An open barbette has no face at all, so the whole anchored total is
        # side/roof plus barbette: none of it is the rotating face of a turret.
        values = ba.estimate(**self.ANCHOR)["values"]
        self.assertEqual(values["face_long_tons"], 0.0)
        self.assertGreater(values["rear_roof_long_tons"], 0.0)


class OverflowBoundaryTests(unittest.TestCase):
    """A positive finite calibre the recovered expression cannot evaluate.

    The declared domain accepts any calibre in ``(0, 500]`` millimetres, so a
    denormal calibre is a *legal* input whose derived expression overflows or
    divides by zero in double precision. That is an unavailable estimate, never
    a raw interpreter error and never a silently clamped or invented calibre.
    """

    BASELINE = dict(year=1910, gun_type="breech_loading", mount_type="turret_barbette",
                    mount_count=4, barrels_per_mount=2, shared_cradle=False,
                    face_mm=150.0, rear_roof_mm=100.0, barbette_mm=75.0,
                    freeboard_m=4.6, super_factor=1.0)
    DENORMAL = (1e-200, 1e-300, 1e-323, 5e-324, 1e-320)

    def test_no_denormal_calibre_raises_a_raw_numerical_error(self):
        for calibre in self.DENORMAL:
            with self.subTest(calibre_mm=calibre):
                try:
                    result = ba.estimate(calibre_mm=calibre, **self.BASELINE)
                except (OverflowError, ZeroDivisionError) as error:
                    self.fail("raw %s for calibre %r" % (type(error).__name__, calibre))

    def test_a_denormal_calibre_is_a_structured_unavailable_result(self):
        for calibre in self.DENORMAL:
            with self.subTest(calibre_mm=calibre):
                result = ba.estimate(calibre_mm=calibre, **self.BASELINE)
                self.assertIsNone(result["values"]["total_long_tons"])
                self.assertIsNone(result["values"]["diameter_ft"])
                self.assertTrue(result["diagnostics"])
                entry = result["diagnostics"][0]
                self.assertEqual(entry["code"], "battery_armour.unavailable")
                self.assertTrue(entry["message"].strip())
                self.assertEqual(entry["field"], "calibre_mm")

    def test_the_provenance_survives_an_unavailable_overflow(self):
        provenance = ba.estimate(calibre_mm=1e-300, **self.BASELINE)["provenance"]
        self.assertEqual(provenance["method"], ba.METHOD_VERSION)
        self.assertEqual(provenance["source_location"], ba.SOURCE_LOCATION)

    def test_the_declared_calibre_is_not_clamped_or_replaced(self):
        # A positive finite calibre is never rewritten to a floor, and never
        # silently treated as the ordinary domain's smallest working value.
        for calibre in (1e-200, 5e-324):
            with self.subTest(calibre_mm=calibre):
                result = ba.estimate(calibre_mm=calibre, **self.BASELINE)
                self.assertEqual(result["values"]["calibre_mm"], calibre)

    def test_the_source_compatible_ordinary_domain_is_untouched(self):
        ordinary = ba.estimate(calibre_mm=152.4, **self.BASELINE)
        self.assertIsNotNone(ordinary["values"]["total_long_tons"])
        self.assertEqual(ordinary["diagnostics"], [])
        self.assertAlmostEqual(ordinary["values"]["total_long_tons"], 245.87606904620486,
                               places=9)


