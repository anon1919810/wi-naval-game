class ReferenceAgreementTests(unittest.TestCase):
    """Every combination of the pinned recovered branches, checked longhand."""

    def test_all_seven_mounts_and_seven_guns_agree_with_the_transcription(self):
        worst = 0.0
        for gun_type, mount_type in itertools.product(ce.GUN_TYPES, ce.MOUNT_TYPES):
            for per_mount in (1, 2, 3, 4, 5):
                for rear in (0.0, 100.0):
                    for cradle in ((False, True) if per_mount >= 2 else (False,)):
                        with self.subTest(gun=gun_type, mount=mount_type,
                                          per_mount=per_mount, rear=rear, cradle=cradle):
                            expected = reference_armour(
                                203.2, 1875, gun_type, mount_type, 3, per_mount, cradle,
                                200.0, rear, 150.0, 5.0, 1.2)
                            values = ba.estimate(
                                calibre_mm=203.2, year=1875, gun_type=gun_type,
                                mount_type=mount_type, mount_count=3,
                                barrels_per_mount=per_mount, shared_cradle=cradle,
                                face_mm=200.0, rear_roof_mm=rear, barbette_mm=150.0,
                                freeboard_m=5.0, super_factor=1.2)["values"]
                            for key, want in expected.items():
                                error = relative(values[key], want)
                                worst = max(worst, error)
                                self.assertLessEqual(error, 1e-5, "%s %s" % (key, want))
        self.assertLess(worst, 1e-5)

    def test_mount_counts_and_years_agree_with_the_transcription(self):
        for mounts, year, calibre in itertools.product((1, 2, 7, 40), (1850, 1875, 1890, 1918),
                                                       (76.2, 152.4, 305.0)):
            with self.subTest(mounts=mounts, year=year, calibre=calibre):
                expected = reference_armour(calibre, year, "breech_loading", "turret_barbette",
                                            mounts, 3, True, 152.4, 88.9, 63.5, 3.9, 1.0)
                values = ba.estimate(calibre_mm=calibre, year=year,
                                     gun_type="breech_loading", mount_type="turret_barbette",
                                     mount_count=mounts, barrels_per_mount=3,
                                     shared_cradle=True, face_mm=152.4, rear_roof_mm=88.9,
                                     barbette_mm=63.5, freeboard_m=3.9,
                                     super_factor=1.0)["values"]
                for key, want in expected.items():
                    self.assertLessEqual(relative(values[key], want), 1e-5, key)

    def test_freeboard_and_super_factor_boundaries_are_reproduced(self):
        for freeboard, factor in itertools.product((0.0, 0.01, 50.0, 100.0), (0.0, 0.5, 10.0)):
            with self.subTest(freeboard=freeboard, super_factor=factor):
                expected = reference_armour(152.4, 1918, "muzzle_loading", "open_barbette",
                                            4, 2, False, 100.0, 0.0, 100.0, freeboard, factor)
                values = ba.estimate(calibre_mm=152.4, year=1918,
                                     gun_type="muzzle_loading", mount_type="open_barbette",
                                     mount_count=4, barrels_per_mount=2, shared_cradle=False,
                                     face_mm=100.0, rear_roof_mm=0.0, barbette_mm=100.0,
                                     freeboard_m=freeboard, super_factor=factor)["values"]
                for key, want in expected.items():
                    self.assertLessEqual(relative(values[key], want), 1e-5, key)


class RecoveredQuirkTests(unittest.TestCase):
    """The three source quirks that look like mistakes and are not corrected."""

    def test_the_barbette_coefficient_is_applied_twice(self):
        # A single-factor rewrite would halve every barbette result, so the
        # difference is asserted rather than described.
        values = run(mount_type="turret_barbette", barrels_per_mount=2,
                     mount_count=4)["values"]
        expected = reference_armour(152.4, 1918, "breech_loading", "turret_barbette", 4, 2,
                                    False, 150.0, 100.0, 75.0, 4.6, 1.0)["barbette_long_tons"]
        single_factor = 2.0 * expected
        self.assertGreater(expected, 0.0)
        self.assertAlmostEqual(values["barbette_long_tons"], expected, places=9)
        self.assertLess(values["barbette_long_tons"], single_factor * 0.9)
        self.assertAlmostEqual(values["barbette_long_tons"], single_factor / 2.0, places=9)

    def test_the_barbette_year_factor_is_the_fourth_root_not_the_square_root(self):
        year = 1875
        values = run(year=year, mount_type="turret_barbette")["values"]
        self.assertAlmostEqual(values["barbette_date_factor"],
                               (1.0 - (1890.0 - year) / 66.666664) ** 0.25, places=12)
        self.assertNotAlmostEqual(values["barbette_date_factor"],
                                  math.sqrt(1.0 - (1890.0 - year) / 66.666664), places=6)

    def test_the_low_mount_branch_leaves_the_barbette_mount_count_uncapped(self):
        # A casemate is a 0.5 mount adjustment with a non-zero barbette
        # coefficient, so it reaches the recovered low-mount branch. That branch
        # writes perMountG1 instead of perMounts, leaving five barrels per mount
        # uncapped there while a 1.0 adjustment mount caps it at four.
        low = run(mount_type="casemate", barrels_per_mount=5, mount_count=4)["values"]
        high = run(mount_type="turret_barbette", barrels_per_mount=5, mount_count=4)["values"]
        self.assertEqual(low["barbette_per_mounts"], 5)
        self.assertEqual(high["barbette_per_mounts"], 4)
        uncapped = reference_armour(152.4, 1918, "breech_loading", "casemate", 4, 5, False,
                                    150.0, 100.0, 75.0, 4.6, 1.0)["barbette_long_tons"]
        self.assertAlmostEqual(low["barbette_long_tons"], uncapped, places=9)
        # The bracketing factor at four instead of five would be this much larger.
        capped_would_be = uncapped * (1.0 - (4.0 - 2.0) / 6.0) / (1.0 - (5.0 - 2.0) / 6.0)
        self.assertNotAlmostEqual(low["barbette_long_tons"], capped_would_be, places=3)

    def test_a_shared_cradle_reduces_the_diameter_by_a_tenth(self):
        plain = run(shared_cradle=False)["values"]["diameter_ft"]
        cradled = run(shared_cradle=True)["values"]["diameter_ft"]
        self.assertAlmostEqual(cradled, plain * 0.9, places=12)
        self.assertEqual(run(shared_cradle=True)["values"]["shared_cradle_diameter_factor"], 0.9)

    def test_the_shared_cradle_reduction_stops_at_one_inch_of_calibre(self):
        values = ba.estimate(calibre_mm=20.0, year=1918, gun_type="automatic",
                             mount_type="casemate", mount_count=2, barrels_per_mount=2,
                             shared_cradle=True, face_mm=10.0, rear_roof_mm=5.0,
                             barbette_mm=5.0, freeboard_m=2.0, super_factor=1.0)["values"]
        self.assertEqual(values["shared_cradle_diameter_factor"], 1.0)
        self.assertAlmostEqual(values["diameter_ft"],
                               reference_armour(20.0, 1918, "automatic", "casemate", 2, 2, True,
                                                10.0, 5.0, 5.0, 2.0, 1.0)["diameter_ft"],
                               places=12)

    def test_a_coles_turret_doubles_the_gun_house_height(self):
        # A six-inch gun sits under the recovered 7.5 ft floor, so a larger
        # calibre is used to observe the branch at all.
        low = run(calibre_mm=406.4, mount_type="deck_hoist")["values"]["gun_house_height_ft"]
        high = run(calibre_mm=406.4, mount_type="coles_turret")["values"]["gun_house_height_ft"]
        self.assertEqual(high, 2 * low)
        self.assertEqual(low, 10.0)
        self.assertEqual(high, 20.0)

    def test_the_gun_house_height_never_falls_below_seven_and_a_half_feet(self):
        self.assertEqual(ba.estimate(calibre_mm=25.4, year=1918, gun_type="muzzle_loading",
                                     mount_type="deck_hoist", mount_count=2,
                                     barrels_per_mount=1, shared_cradle=False, face_mm=10.0,
                                     rear_roof_mm=10.0, barbette_mm=0.0,
                                     freeboard_m=2.0, super_factor=1.0
                                     )["values"]["gun_house_height_ft"], 7.5)

    def test_an_open_barbette_has_no_face_but_still_has_side_and_roof_mass(self):
        # The recovered face coefficient for an open barbette is a constant zero,
        # while the side/roof expression keeps its 0.75 disc term even when the
        # area coefficient is zero. That asymmetry is the source's own.
        values = run(mount_type="open_barbette", face_mm=300.0, rear_roof_mm=300.0)["values"]
        self.assertEqual(values["face_long_tons"], 0.0)
        self.assertEqual(values["face_coefficient"], 0.0)
        self.assertEqual(values["rear_roof_coefficient"], 0.0)
        self.assertGreater(values["rear_roof_long_tons"], 0.0)
        self.assertGreater(values["barbette_long_tons"], 0.0)

    def test_a_coles_turret_rear_mass_is_the_disc_area_only(self):
        values = run(mount_type="coles_turret", rear_roof_mm=100.0)["values"]
        self.assertAlmostEqual(
            values["rear_roof_long_tons"],
            math.pi * (values["diameter_ft"] / 2) ** 2 * 4 * (100.0 / 25.4) * INCH, places=12)


class ResultShapeTests(unittest.TestCase):
    def test_every_returned_number_is_finite_and_non_negative(self):
        for calibre, mounts, per_mount in itertools.product((25.4, 152.4, 406.4),
                                                           (1, 3, 12), (1, 2, 3, 4, 5)):
            for cradle in ((False, True) if per_mount >= 2 else (False,)):
                values = run(calibre_mm=calibre, mount_count=mounts,
                             barrels_per_mount=per_mount, shared_cradle=cradle)["values"]
                for key, value in values.items():
                    if isinstance(value, bool) or value is None or isinstance(value, str):
                        continue
                    self.assertTrue(math.isfinite(value), (key, value))
                    self.assertGreaterEqual(value, 0.0, (key, value))

    def test_the_total_is_the_sum_of_the_three_components(self):
        values = run()["values"]
        self.assertAlmostEqual(
            values["total_long_tons"],
            values["face_long_tons"] + values["rear_roof_long_tons"]
            + values["barbette_long_tons"], places=12)

    def test_no_armour_at_all_is_a_known_zero_not_an_unknown(self):
        values = run(face_mm=0.0, rear_roof_mm=0.0, barbette_mm=0.0)["values"]
        self.assertEqual(values["total_long_tons"], 0.0)
        self.assertEqual(ba.estimate(**dict(BASE, face_mm=0.0, rear_roof_mm=0.0,
                                            barbette_mm=0.0))["diagnostics"], [])

    def test_thickness_changes_move_the_estimate(self):
        thin = run(face_mm=100.0, rear_roof_mm=60.0, barbette_mm=40.0)["values"]["total_long_tons"]
        thick = run(face_mm=200.0, rear_roof_mm=120.0, barbette_mm=80.0)["values"]["total_long_tons"]
        self.assertGreater(thick, thin)

    def test_the_estimate_does_not_read_any_ammunition_input(self):
        import inspect
        names = set(inspect.signature(ba.estimate).parameters)
        self.assertFalse(names & {"rounds_per_gun", "shell_mass_kg", "barrel_calibres",
                                  "broadside_guns"})


class UnknownInputTests(unittest.TestCase):
    """Missing is unknown. It is never read as zero and never blocks the rest."""

    def test_an_unknown_thickness_leaves_only_its_own_component_unknown(self):
        result = ba.estimate(**dict(BASE, barbette_mm=None))
        values = result["values"]
        self.assertIsNotNone(values["face_long_tons"])
        self.assertIsNotNone(values["rear_roof_long_tons"])
        self.assertIsNone(values["barbette_long_tons"])
        self.assertIsNone(values["total_long_tons"])
        self.assertTrue(result["diagnostics"])
        self.assertEqual(result["diagnostics"][0]["field"], "barbette_mm")

    def test_an_unknown_rear_thickness_blocks_the_face_only_where_the_source_reads_it(self):
        # An open barbette's face coefficient is a constant zero, so an unknown
        # rear thickness cannot change it.
        open_barbette = ba.estimate(**dict(BASE, mount_type="open_barbette", rear_roof_mm=None))
        self.assertIsNotNone(open_barbette["values"]["face_long_tons"])
        self.assertIsNone(open_barbette["values"]["rear_roof_long_tons"])
        self.assertIsNone(open_barbette["values"]["total_long_tons"])
        # A deck hoist's face coefficient branches on the rear thickness.
        deck_hoist = ba.estimate(**dict(BASE, mount_type="deck_hoist", rear_roof_mm=None))
        self.assertIsNone(deck_hoist["values"]["face_long_tons"])
        self.assertIsNone(deck_hoist["values"]["total_long_tons"])

    def test_an_unknown_machine_gun_needs_the_rear_thickness_but_an_anti_air_gun_does_not(self):
        # A casemate's face coefficient is a constant, so only the machine-gun
        # class still reads the side/roof thickness.
        gun = ba.estimate(**dict(BASE, mount_type="casemate", gun_type="machine_gun",
                                 rear_roof_mm=None))
        self.assertIsNone(gun["values"]["face_long_tons"])
        aa = ba.estimate(**dict(BASE, mount_type="casemate", gun_type="anti_air",
                                rear_roof_mm=None))
        self.assertIsNotNone(aa["values"]["face_long_tons"])
        self.assertAlmostEqual(aa["values"]["face_gun_type_factor"], 0.333, places=12)

    def test_missing_freeboard_or_super_factor_blocks_only_the_barbette(self):
        for field in ("freeboard_m", "super_factor"):
            with self.subTest(field=field):
                result = ba.estimate(**dict(BASE, **{field: None}))
                values = result["values"]
                self.assertIsNotNone(values["face_long_tons"])
                self.assertIsNotNone(values["rear_roof_long_tons"])
                self.assertIsNone(values["barbette_long_tons"])
                self.assertIsNone(values["total_long_tons"])
                self.assertEqual(result["diagnostics"][0]["field"], field)

    def test_a_mount_without_a_barbette_needs_no_freeboard_at_all(self):
        for mount_type in ("broadside", "coles_turret", "deck"):
            with self.subTest(mount_type=mount_type):
                result = ba.estimate(**dict(BASE, mount_type=mount_type, freeboard_m=None,
                                            super_factor=None))
                self.assertEqual(result["values"]["barbette_long_tons"], 0.0)
                self.assertIsNotNone(result["values"]["total_long_tons"])
                self.assertEqual(result["diagnostics"], [])

    def test_a_zero_barbette_thickness_needs_no_freeboard_at_all(self):
        result = ba.estimate(**dict(BASE, barbette_mm=0.0, freeboard_m=None, super_factor=None))
        self.assertEqual(result["values"]["barbette_long_tons"], 0.0)
        self.assertIsNotNone(result["values"]["total_long_tons"])
        self.assertEqual(result["diagnostics"], [])

    def test_a_declared_zero_freeboard_is_a_known_zero_barbette(self):
        # The recovered barbette branch is entered only when freeGun > 0, so a
        # declared zero freeboard is a real zero, not an unknown.
        values = ba.estimate(**dict(BASE, freeboard_m=0.0, super_factor=None))["values"]
        self.assertEqual(values["barbette_long_tons"], 0.0)
        self.assertIsNotNone(values["total_long_tons"])

    def test_every_unavailable_component_names_the_missing_field(self):
        result = ba.estimate(**dict(BASE, face_mm=None, rear_roof_mm=None, barbette_mm=None,
                                    freeboard_m=None, super_factor=None))
        fields = {entry["field"] for entry in result["diagnostics"]}
        self.assertTrue({"face_mm", "rear_roof_mm", "barbette_mm"} <= fields, fields)
        for entry in result["diagnostics"]:
            self.assertTrue(entry["message"].strip())
            self.assertIn(entry["code"], {"battery_armour.unknown", "battery_armour.unsupported"})


class RejectionTests(unittest.TestCase):
    """Wrong type, wrong sign, wrong domain and a fractional count are refused."""

    def test_wrong_types_are_rejected(self):
        for field, bad in (("calibre_mm", "152"), ("year", 1918.0), ("gun_type", "cannon"),
                           ("mount_type", "turret"), ("mount_count", 4.0),
                           ("barrels_per_mount", True), ("shared_cradle", "no"),
                           ("face_mm", []), ("freeboard_m", True), ("super_factor", "high")):
            with self.subTest(field=field, value=bad), self.assertRaises(ValueError):
                ba.estimate(**dict(BASE, **{field: bad}))

