# MainForm.cs:22, the recovered empirical mass constant. It converts the source's
# inch thicknesses into feet inside an expression that is otherwise already in
# feet, so it is not a density and is never rewritten as one.
INCH = 0.0185
# GunControl.cs:22 main.INCH is the recovered empirical mass constant, and
# MainForm.M_PER_FT-equivalent is 0.3048: the recovered freeGun the barbette
# expression reads is in FEET.
M_PER_FT = 0.3048

# GunControl.cs:1238-1274 diameterCalc, five classes keyed by the recovered
# ``gunsInMount`` selector the method receives. ``perMountCalc`` (:636) gives
# those fifteen indices the barrel counts 1, 2, 4, 2, 2, 4, 3, 3, 6, 4, 4, 8,
# 5, 5, 10, and ``weightAdjCalc`` (:480) returns 0.75 for indices 3, 6, 9, 12.
# For one homogeneous row the selectors are 0 without a shared cradle at one
# barrel, 4/7/10/13 without and 3/6/9/12 with one.
DIAMETER_CLASS_BY_SELECTOR = {}
for _index in range(15):
    if _index <= 2:
        DIAMETER_CLASS_BY_SELECTOR[_index] = (1.44, 0.609725)
    elif _index <= 5:
        DIAMETER_CLASS_BY_SELECTOR[_index] = (1.52, 0.4205)
    elif _index <= 8:
        DIAMETER_CLASS_BY_SELECTOR[_index] = (1.64, 0.29)
    elif _index <= 11:
        DIAMETER_CLASS_BY_SELECTOR[_index] = (1.8, 0.2)
    else:
        DIAMETER_CLASS_BY_SELECTOR[_index] = (2.0, 0.14)
SELECTOR = {1: (0, None), 2: (4, 3), 3: (7, 6), 4: (10, 9), 5: (13, 12)}
BARBETTE_COEFFICIENT = {2: 0.6416, 3: 0.5, 4: 0.1, 6: 0.1}


def date_fourth_root(year):
    """GunControl.cs:429 then :1222.

    ``dateGunAdj = sqrt(dateAdjCalc(year))`` and the barbette expression takes
    ``sqrt(dateGunAdj)``, so the barbette year factor is the FOURTH root of the
    date adjustment, not the square root. The square root is what the shell and
    gun mass kernels use.
    """
    return math.sqrt(ce.gun_date_factor(year))


def reference_armour(calibre_mm, year, gun_type, mount_type, mount_count, barrels_per_mount,
                     shared_cradle, face_mm, rear_roof_mm, barbette_mm,
                     freeboard_m=None, super_factor=None):
    """A longhand transcription of GunControl.cs:1127-1233 for ONE row.

    A homogeneous row is a single mount group, so the source's second group is
    empty: ``mountsG1 = mount_count``, ``mountsG2 = 0``, ``perMountG1 =
    barrels_per_mount`` and ``perMountG2 = 0``. The integer average the source
    takes of those two groups is therefore exactly the row's barrels per mount.

    Written independently of the module under test so that a shared structural
    mistake cannot hide.
    """
    calibre = calibre_mm / 25.4
    gun_index = ce.GUN_TYPES.index(gun_type)
    mount_index = ce.MOUNT_TYPES.index(mount_type)
    plain, shared = SELECTOR[barrels_per_mount]
    selector = shared if shared_cradle else plain
    weight_adjustment = 0.75 if selector in (3, 6, 9, 12) else 1.0
    num, num2 = DIAMETER_CLASS_BY_SELECTOR[selector]
    diameter = num * calibre * (1 + (1 / calibre) ** num2)
    if calibre < 12:
        diameter += 12 / calibre
    if calibre > 1 and weight_adjustment < 1:
        diameter *= 0.9

    if mount_index == 1:
        height = max(7.5, 0.625 * calibre * 2)
    else:
        height = max(7.5, 0.625 * calibre)

    summed = diameter * mount_count
    disc = math.pi * (diameter / 2) ** 2 * mount_count

    if mount_index in (0, 6):
        face_coefficient = 1.0
    elif mount_index == 1:
        face_coefficient = math.pi / 2
    elif mount_index == 2:
        face_coefficient = 0.0
    elif rear_roof_mm == 0:
        face_coefficient = 1.5
    else:
        face_coefficient = 0.5
    face = face_coefficient * summed * height * (face_mm / 25.4) * INCH
    if gun_index == 3 or (gun_index == 6 and rear_roof_mm == 0):
        face *= 0.333

    if mount_index == 1:
        back = disc
    else:
        back_coefficient = 2.5 if 2 < mount_index < 6 else 0.0
        back = back_coefficient * summed * height + disc * 0.75
    back *= (rear_roof_mm / 25.4) * INCH

    barrels = mount_count * barrels_per_mount
    if freeboard_m > 0:
        per_mounts = barrels_per_mount
        if ce.MOUNT_ADJUSTMENT[mount_index] > 0.5:
            per_mounts = min(4, per_mounts)
        coefficient = BARBETTE_COEFFICIENT.get(mount_index, 0.0)
        # The recovered expression multiplies its own barbette coefficient twice
        # and reads the position-weighted freeboard in FEET.
        barbette = (1 - (per_mounts - 2) / 6) * (barbette_mm / 25.4 * barrels
                                                * calibre ** 1.2 * coefficient
                                                * (freeboard_m / M_PER_FT) / 16
                                                * super_factor * coefficient * 2
                                                * date_fourth_root(year))
    else:
        barbette = 0.0
    return {"diameter_ft": diameter, "gun_house_height_ft": height,
            "face_long_tons": face, "rear_roof_long_tons": back,
            "barbette_long_tons": barbette,
            "total_long_tons": face + back + barbette}


BASE = dict(calibre_mm=152.4, year=1918, gun_type="breech_loading", mount_type="deck_hoist",
            mount_count=4, barrels_per_mount=2, shared_cradle=False,
            face_mm=150.0, rear_roof_mm=100.0, barbette_mm=75.0,
            freeboard_m=4.6, super_factor=1.0)


def run(**overrides):
    arguments = dict(BASE)
    arguments.update(overrides)
    return ba.estimate(**arguments)


def relative(actual, expected):
    if expected == 0:
        return abs(actual)
    return abs(actual - expected) / abs(expected)


