"""Battery gun-house and barbette armour mass kernel.

Every expected value in this file is either a hand-derived arithmetic case
written out below or a longhand transcription of the recovered
``GunControl.cs:1127-1294`` expression kept in ``reference_armour``. Nothing is
generated by the module under test, and nothing here claims to be a vector
produced by running the original assembly: reproducing the original binary is
the accepting reviewer's separate job, with its own provenance.
"""

