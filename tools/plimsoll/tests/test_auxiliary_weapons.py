class DeclarationTests(unittest.TestCase):

    def test_absent_and_null_are_disabled_and_return_an_empty_list(self):
        self.assertEqual(aw.validate_configs(None), [])
        self.assertEqual(aw.validate_configs([]), [])

    def test_a_non_array_section_is_refused(self):
        for raw in ({"id": "x"}, "torpedo", 3):
            with self.assertRaises(aw.AuxiliaryValidationError):
                aw.validate_configs(raw)

    def test_more_than_fifty_records_are_refused_and_fifty_are_accepted(self):
        raw = [{"id": "g%d" % index, "kind": "mine"} for index in range(51)]
        with self.assertRaises(aw.AuxiliaryValidationError):
            aw.validate_configs(raw)
        raw = [{"id": "g%d" % index, "kind": "mine"} for index in range(50)]
        self.assertEqual(len(aw.validate_configs(raw)), 50)

    def test_a_wrong_id_and_a_duplicate_id_are_refused(self):
        for identity in ("", "a b", "x" * 81, 7):
            with self.assertRaises(aw.AuxiliaryValidationError):
                aw.validate_configs([{"id": identity, "kind": "mine"}])
        with self.assertRaises(aw.AuxiliaryValidationError):
            aw.validate_configs([{"id": "same", "kind": "mine"},
                                 {"id": "same", "kind": "torpedo"}])

    def test_an_unknown_kind_is_refused(self):
        with self.assertRaises(aw.AuxiliaryValidationError):
            aw.validate_configs([{"id": "x", "kind": "gun"}])

    def test_a_field_that_does_not_belong_to_the_chosen_kind_is_refused(self):
        with self.assertRaises(aw.AuxiliaryValidationError):
            aw.validate_configs([{"id": "x", "kind": "torpedo", "unit_mass_kg": 5.0}])
        with self.assertRaises(aw.AuxiliaryValidationError):
            aw.validate_configs([{"id": "x", "kind": "mine", "diameter_mm": 500.0}])

    def test_a_fractional_count_is_refused_rather_than_truncated(self):
        for value in (1.5, 10.0, True, "10"):
            with self.subTest(value=value):
                with self.assertRaises(aw.AuxiliaryValidationError):
                    aw.validate_configs([{"id": "x", "kind": "mine", "count": value}])

    def test_the_declared_bounds_are_inclusive_at_both_ends(self):
        aw.validate_configs([{"id": "x", "kind": "torpedo", "count": 1000000,
                              "loads": 0, "location_index": 8, "diameter_mm": 2000.0,
                              "length_m": 100.0}])
        aw.validate_configs([{"id": "x", "kind": "mine", "unit_mass_kg": 100000.0,
                              "location_index": 3}])
        for extra in ({"count": 1000001}, {"diameter_mm": 2000.001}, {"length_m": 100.001},
                      {"unit_mass_kg": 100000.001}, {"count": -1}, {"diameter_mm": -0.5}):
            with self.subTest(extra=extra):
                with self.assertRaises(aw.AuxiliaryValidationError):
                    aw.validate_configs([dict({"id": "x", "kind": "torpedo"}, **extra)])

    def test_the_location_range_is_the_recovered_table_of_each_kind(self):
        aw.validate_configs([{"id": "x", "kind": "torpedo", "location_index": 8}])
        for kind in ("mine", "depth_charge"):
            aw.validate_configs([{"id": "x", "kind": kind, "location_index": 3}])
            with self.assertRaises(aw.AuxiliaryValidationError):
                aw.validate_configs([{"id": "x", "kind": kind, "location_index": 4}])
        with self.assertRaises(aw.AuxiliaryValidationError):
            aw.validate_configs([{"id": "x", "kind": "torpedo", "location_index": 9}])

    def test_every_fact_and_binding_may_be_null_in_a_saved_draft(self):
        records = aw.validate_configs([{"id": "draft", "kind": "mine"}])
        self.assertIsNone(records[0]["item_id"])
        self.assertIsNone(records[0]["count"])
        self.assertEqual(aw.evaluate(records[0], {})["status"], "unavailable")

    def test_a_blank_provenance_note_is_absent_and_never_a_claim(self):
        self.assertIsNone(
            aw.validate_configs([{"id": "d", "kind": "mine", "source": "  "}])[0]["source"])
        with self.assertRaises(aw.AuxiliaryValidationError):
            aw.validate_configs([{"id": "d", "kind": "mine", "source": 7}])

    def test_changing_kind_keeps_the_common_fields_and_drops_the_rest(self):
        # What a normal editor does when the reader changes the kind: the identity,
        # the binding and the note survive, the kind-specific facts do not.
        before = {"id": "group", "kind": "torpedo", "system_id": "weapons.aux",
                  "item_id": "weapons.aux.group", "source": "declared",
                  "count": 6, "loads": 4, "location_index": 5,
                  "diameter_mm": 533.4, "length_m": 7.62}
        after = dict(before, kind="mine", unit_mass_kg=136.0, location_index=None, loads=None)
        for field in ("diameter_mm", "length_m"):
            after.pop(field)
        changed = aw.validate_configs([after])[0]
        self.assertEqual(changed["id"], before["id"])
        self.assertEqual(changed["system_id"], before["system_id"])
        self.assertEqual(changed["item_id"], before["item_id"])
        self.assertEqual(changed["source"], before["source"])
        self.assertEqual(changed["count"], before["count"])
        self.assertEqual(changed["kind"], "mine")
        self.assertEqual(changed["unit_mass_kg"], 136.0)
        self.assertIsNone(changed["diameter_mm"])
        # The torpedo reading is gone and the mine reading is in its place.
        self.assertEqual(aw.evaluate(changed, CONTEXT)['status'], 'unavailable')


