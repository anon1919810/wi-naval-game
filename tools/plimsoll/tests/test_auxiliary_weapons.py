class MethodIdentityTests(unittest.TestCase):

    def test_the_kernel_carries_its_own_method_and_source_identity(self):
        self.assertEqual(aw.METHOD_VERSION, "sps-3b3-auxiliary-weapons-v1")
        self.assertEqual(aw.SOURCE_LOCATION, "WeaponControl.cs:325-534")
        self.assertEqual(aw.SOURCE_ASSEMBLY, "SpringSharpMono 3.0.3032.29945")
        self.assertEqual(aw.SOURCE_SHA256,
                         "82ecc3fedf76af222dd13ad68258f3ae92146e9fad7dc6a4a96f3270fccf71fc")
        for constant in ("SOURCE_SCOPE", "SOURCE_LOCATION"):
            self.assertTrue(getattr(aw, constant))
        self.assertIn("not weapon space", aw.SOURCE_SCOPE)

    def test_there_are_exactly_three_kinds_on_one_role(self):
        self.assertEqual(aw.KINDS, ("torpedo", "mine", "depth_charge"))
        self.assertEqual(aw.TARGET_ROLE, "other")

    def test_the_result_shape_is_the_documented_contract(self):
        result = reading("torpedo", **TORPEDO)
        self.assertEqual(sorted(result), ["diagnostics", "id", "kind", "method_version",
                                          "origin", "provenance", "status", "values"])
        self.assertEqual(sorted(result["values"]), ["mass_t", "mount_factor",
                                                    "mount_long_tons", "total_long_tons",
                                                    "weapon_long_tons"])
        self.assertEqual(result["method_version"], aw.METHOD_VERSION)
        self.assertEqual(result["status"], "available")
        for key in ("kernel", "formula", "source_sha256", "assumptions", "context", "inputs"):
            self.assertIn(key, result["provenance"]), key


