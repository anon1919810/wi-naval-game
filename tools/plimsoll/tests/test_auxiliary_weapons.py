class TorpedoMassTests(unittest.TestCase):

    def test_the_recovered_expression_is_reproduced(self):
        result = reading("torpedo", **TORPEDO)
        expected = reference_torpedo(6, 21 * INCH_MM, 25 * M_PER_FT, YEAR)
        self.assertEqual(result["status"], "available")
        self.assertTrue(close(result["values"]["weapon_long_tons"], expected))

    def test_the_1907_age_floor_is_the_only_place_the_year_enters_the_denominator(self):
        after = reading("torpedo", **dict(TORPEDO, count=1),
                        context={"hull_year": 1907})["values"]["weapon_long_tons"]
        much_later = reading("torpedo", **dict(TORPEDO, count=1),
                             context={"hull_year": 1950})["values"]["weapon_long_tons"]
        self.assertTrue(close(much_later - after, .004 * (1950 - 1907)))
        for year in (1900, 1906, 1907):
            with self.subTest(year=year):
                result = reading("torpedo", **TORPEDO, context={"hull_year": year})
                self.assertTrue(close(
                    result["values"]["weapon_long_tons"],
                    reference_torpedo(6, 21 * INCH_MM, 25 * M_PER_FT, year)))
        self.assertLess(reading("torpedo", **dict(TORPEDO, count=1),
                                context={"hull_year": 1900})["values"]["weapon_long_tons"],
                        after)

    def test_the_year_term_is_not_floored_and_may_be_negative(self):
        early = reading("torpedo", **dict(TORPEDO, count=1),
                        context={"hull_year": 1800})["values"]["weapon_long_tons"]
        later = reading("torpedo", **dict(TORPEDO, count=1),
                        context={"hull_year": 1912})["values"]["weapon_long_tons"]
        self.assertIsNone(early)
        self.assertGreater(later, 0.0)

    def test_an_unsupported_or_fractional_year_is_refused(self):
        for year in (1799, 2101, 1912.5):
            with self.subTest(year=year):
                result = reading("torpedo", **TORPEDO, context={"hull_year": year})
                self.assertEqual(result["status"], "unavailable")
                self.assertIsNone(result["values"]["total_long_tons"])

    def test_a_known_zero_in_the_recovered_guard_is_a_determined_zero(self):
        for zero in ({"count": 0}, {"diameter_mm": 0.0}, {"length_m": 0.0}):
            with self.subTest(zero=zero):
                fields = dict(TORPEDO, **zero)
                result = aw.evaluate(record("torpedo", **fields), {})
                self.assertEqual(result["status"], "available")
                self.assertEqual(result["values"]["weapon_long_tons"], 0.0)
                self.assertEqual(result["values"]["mount_long_tons"], 0.0)
                self.assertEqual(result["values"]["total_long_tons"], 0.0)
                self.assertEqual(result["values"]["mass_t"], 0.0)
                # A determined zero weapon needs no hull year.
                self.assertIsNone(result["provenance"]["context"]["hull_year"])

    def test_loads_is_never_a_weight_multiplier_for_a_torpedo(self):
        without = reading("torpedo", **dict(TORPEDO, loads=None))
        with_zero = reading("torpedo", **dict(TORPEDO, loads=0))
        with_many = reading("torpedo", **dict(TORPEDO, loads=999))
        for result in (with_zero, with_many):
            self.assertEqual(result["status"], "available")
            self.assertTrue(close(result["values"]["weapon_long_tons"],
                                  without["values"]["weapon_long_tons"]))

    def test_all_nine_recovered_locations_use_the_recovered_torpedo_factors(self):
        expected = {0: 0.25, 1: 1.0, 2: 1.0, 3: 0.25, 4: 1.0, 5: 1.0, 6: 1.0, 7: 1.0,
                    8: 0.25}
        self.assertEqual(aw.MOUNT_FACTORS["torpedo"], expected)
        weapon = reference_torpedo(6, 21 * INCH_MM, 25 * M_PER_FT, YEAR)
        for location, factor in expected.items():
            with self.subTest(location=location):
                values = reading("torpedo", **dict(TORPEDO, location_index=location))["values"]
                self.assertEqual(values["mount_factor"], factor)
                self.assertTrue(close(values["mount_long_tons"], weapon * factor))
                self.assertTrue(close(values["total_long_tons"],
                                      weapon * (1.0 + factor)))

    def test_a_positive_weapon_without_a_location_has_no_complete_estimate(self):
        result = reading("torpedo", **dict(TORPEDO, location_index=None))
        self.assertEqual(result["status"], "unavailable")
        self.assertIsNotNone(result["values"]["weapon_long_tons"])
        self.assertIsNone(result["values"]["mount_long_tons"])
        self.assertIsNone(result["values"]["total_long_tons"])
        self.assertTrue(any(d["field"] == "location_index" for d in result["diagnostics"]))

    def test_an_unknown_dimension_is_unknown_and_never_read_as_zero(self):
        for missing in ("count", "diameter_mm", "length_m"):
            with self.subTest(missing=missing):
                fields = dict(TORPEDO)
                fields[missing] = None
                result = reading("torpedo", **fields)
                self.assertEqual(result["status"], "unavailable")
                self.assertTrue(any(d["field"] == missing for d in result["diagnostics"]))


class UnitMassTests(unittest.TestCase):

    def test_a_mine_and_a_depth_charge_use_the_recovered_unit_mass_expression(self):
        for kind, fields in (("mine", MINE), ("depth_charge", DEPTH_CHARGE)):
            with self.subTest(kind=kind):
                result = reading(kind, **fields)
                expected = reference_unit_mass(fields["count"], fields["loads"],
                                               fields["unit_mass_kg"])
                self.assertEqual(result["status"], "available")
                self.assertTrue(close(result["values"]["weapon_long_tons"], expected))

    def test_the_reload_count_is_added_to_the_carried_count(self):
        more = reading("mine", **dict(MINE, loads=120))
        fewer = reading("mine", **MINE)
        self.assertTrue(close(
            more["values"]["weapon_long_tons"],
            fewer["values"]["weapon_long_tons"] * (240 / 180)))

    def test_a_zero_reload_count_is_never_rewritten_to_one(self):
        # The recovered page rewrites a zero loads to one before its deck-area
        # expression. That mutation is not carried over.
        zero = reading("mine", **dict(MINE, loads=0))
        explicit = reading("mine", **dict(MINE, loads=0, count=MINE["count"]))
        self.assertTrue(close(zero["values"]["weapon_long_tons"],
                              reference_unit_mass(MINE["count"], 0, MINE["unit_mass_kg"])))
        self.assertEqual(zero["values"]["weapon_long_tons"],
                         explicit["values"]["weapon_long_tons"])
        self.assertLess(zero["values"]["weapon_long_tons"],
                        reading("mine", **MINE)["values"]["weapon_long_tons"])

    def test_unknown_reloads_are_not_zero_reloads(self):
        result = reading("mine", **dict(MINE, loads=None))
        self.assertEqual(result["status"], "unavailable")
        self.assertIsNone(result["values"]["weapon_long_tons"])
        self.assertTrue(any(d["field"] == "loads" for d in result["diagnostics"]))

    def test_a_known_zero_mass_or_a_known_zero_total_count_is_a_determined_zero(self):
        for fields in ({"unit_mass_kg": 0.0, "count": 5, "loads": 2, "location_index": 1},
                       {"unit_mass_kg": 136.0, "count": 0, "loads": 0, "location_index": 1}):
            with self.subTest(fields=fields):
                result = aw.evaluate(record("mine", **fields), {})
                self.assertEqual(result["status"], "available")
                self.assertEqual(result["values"]["total_long_tons"], 0.0)

    def test_a_known_zero_count_with_unknown_reloads_is_still_unknown(self):
        result = reading("mine", count=0, loads=None, unit_mass_kg=136.0,
                         location_index=1)
        self.assertEqual(result["status"], "unavailable")

    def test_all_four_recovered_mine_and_depth_charge_locations_are_read(self):
        self.assertEqual(aw.MOUNT_FACTORS["mine"], {0: 0.25, 1: 1.0, 2: 1.0, 3: 1.0})
        self.assertEqual(aw.MOUNT_FACTORS["depth_charge"],
                         {0: 0.25, 1: 0.5, 2: 0.5, 3: 10.0})
        for kind, fields in (("mine", MINE), ("depth_charge", DEPTH_CHARGE)):
            weapon = reference_unit_mass(fields["count"], fields["loads"],
                                         fields["unit_mass_kg"])
            for location, factor in aw.MOUNT_FACTORS[kind].items():
                with self.subTest(kind=kind, location=location):
                    values = reading(kind, **dict(fields, location_index=location))["values"]
                    self.assertEqual(values["mount_factor"], factor)
                    self.assertTrue(close(values["total_long_tons"],
                                          weapon * (1.0 + factor)))

    def test_the_unit_mass_is_the_full_unit_and_not_the_charge(self):
        # The recovered expression reads one unit mass for the whole weapon; there
        # is no separate explosive charge anywhere in this kernel.
        result = reading("mine", **MINE)
        self.assertNotIn("explosive", json.dumps(result["provenance"]["inputs"]))
        self.assertTrue(close(result["values"]["weapon_long_tons"],
                              180 * (300.0 / 2240.0)))

    def test_a_pounds_and_kilograms_declaration_is_the_same_weapon(self):
        pounds = reading("mine", count=180, loads=0, location_index=1,
                         unit_mass_kg=300 * POUND_KG)
        kilograms = reading("mine", count=180, loads=0, location_index=1,
                            unit_mass_kg=136.077711)
        self.assertAlmostEqual(pounds["values"]["total_long_tons"],
                               kilograms["values"]["total_long_tons"], places=9)


class SharedReadingTests(unittest.TestCase):

    def test_the_combined_total_is_the_sum_of_the_two_source_terms(self):
        for kind, fields in (("torpedo", TORPEDO), ("mine", MINE),
                             ("depth_charge", DEPTH_CHARGE)):
            with self.subTest(kind=kind):
                values = reading(kind, **fields)["values"]
                self.assertTrue(close(values["total_long_tons"],
                                      values["weapon_long_tons"] + values["mount_long_tons"]))
                breakdown = aw.component_breakdown(values, kind)
                self.assertEqual(sorted(breakdown), ["mount_long_tons", "weapon_long_tons"])

    def test_the_returned_tonnes_are_the_returned_long_tons_converted_once(self):
        values = reading("torpedo", **TORPEDO)["values"]
        self.assertTrue(close(values["mass_t"],
                              values["total_long_tons"] * LONG_TON_KG / 1000.0))

    def test_every_model_input_is_a_flat_scalar_of_the_chosen_kind(self):
        inputs = reading("torpedo", **TORPEDO)["provenance"]["inputs"]
        self.assertIn("diameter_mm", inputs)
        self.assertNotIn("unit_mass_kg", inputs)
        for key, value in inputs.items():
            self.assertIsInstance(value, (int, float), key)
            self.assertFalse(isinstance(value, bool), key)
            self.assertTrue(math.isfinite(value), key)

    def test_the_whole_declaration_travels_as_one_scalar_origin_text(self):
        result = reading("depth_charge", **DEPTH_CHARGE)
        self.assertIsInstance(result["origin"], str)
        payload = json.loads(result["origin"])
        self.assertEqual(payload["record"]["kind"], "depth_charge")
        self.assertEqual(payload["context"]["hull_year"], YEAR)
        json.dumps(payload, allow_nan=False)

    def test_a_context_fact_provenance_travels_into_the_result(self):
        result = reading("torpedo", context={"hull_year": {
            "value": YEAR, "source": "declared concept hull year", "estimate": False}},
            **TORPEDO)
        origin = result["provenance"]["context"]["hull_year"]
        self.assertEqual(origin["source"], "declared concept hull year")
        self.assertIs(origin["estimate"], False)

    def test_no_kind_reports_no_expression_rather_than_a_zero(self):
        result = aw.evaluate({"id": "x", "kind": None, "count": 6}, CONTEXT)
        self.assertEqual(result["status"], "unavailable")
        self.assertTrue(any("no auxiliary weapon kind is chosen" in d["message"]
                            for d in result["diagnostics"]))
        self.assertIsNone(result["values"]["total_long_tons"])

    def test_the_assumptions_state_the_scope_refusals(self):
        text = " ".join(aw.ASSUMPTIONS)
        for phrase in ("never used as a weight multiplier", "reload", "'other'", "space"):
            self.assertIn(phrase, text)


