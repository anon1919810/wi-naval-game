"""The recovered auxiliary weapons kernel: three kinds, two mass expressions.

Every expected number here comes from ``reference_torpedo`` / ``reference_unit_mass``
below, a longhand transcription of the recovered ``WeaponControl.cs`` expressions
written without the module under test, or from arithmetic written out in the test
itself.

No original-assembly vector exists for this kernel yet: the source worker will add
one. Nothing here is generated by the module under test, and nothing here claims
weapon space, a firing arc, reload geometry, explosive performance or whole-program
parity.
"""

import json
import math
from pathlib import Path
import sys
import unittest

HERE = Path(__file__).resolve().parent
PKG = HERE.parent
if str(PKG) not in sys.path:
    sys.path.insert(0, str(PKG))

import auxiliary_weapons as aw  # noqa: E402

INCH_MM = 25.4
M_PER_FT = 0.3048
POUND_KG = 0.45359237
POUNDS_PER_LONG_TON = 2240.0
LONG_TON_KG = 1016.0469088

# One synthetic hull year well inside the recovered domain.
YEAR = 1912
CONTEXT = {"hull_year": YEAR}

# A 21 inch, 25 foot torpedo tube group: the same weapon declared canonically.
TORPEDO = {"count": 6, "loads": 4, "location_index": 5,
           "diameter_mm": 21 * INCH_MM, "length_m": 25 * M_PER_FT}
MINE = {"count": 120, "loads": 60, "location_index": 2, "unit_mass_kg": 300 * POUND_KG}
DEPTH_CHARGE = {"count": 30, "loads": 10, "location_index": 3,
                "unit_mass_kg": 100 * POUND_KG}


def reference_torpedo(count, diameter_mm, length_m, year):
    """WeaponControl.cs:360-370, transcribed verbatim."""
    age = 0 if year >= 1907 else 1907 - year
    each = (math.pi * (diameter_mm / INCH_MM) ** 2 * (length_m / M_PER_FT)
            / ((age + 25.0) * 937.0) + 0.004 * (year - 1890))
    return each * count


def reference_unit_mass(count, loads, unit_mass_kg):
    """WeaponControl.cs:377-380, transcribed verbatim."""
    return (count + loads) * (unit_mass_kg / POUND_KG) / POUNDS_PER_LONG_TON


def record(kind, **fields):
    declared = {"id": "group", "kind": kind}
    declared.update(fields)
    return aw.validate_configs([declared])[0]


def reading(kind, context=None, **fields):
    return aw.evaluate(record(kind, **fields), CONTEXT if context is None else context)


def close(actual, expected, tolerance=1e-12):
    if expected == 0:
        return abs(actual) <= tolerance
    return abs(actual - expected) <= tolerance * abs(expected)


