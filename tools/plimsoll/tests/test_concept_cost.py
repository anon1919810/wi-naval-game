class MethodIdentityTests(unittest.TestCase):

    def test_the_reading_carries_its_own_method_and_source_identity(self):
        self.assertEqual(cc.METHOD_VERSION, "sps-3b3-cost-v1")
        self.assertEqual(cc.SOURCE_ASSEMBLY, "SpringSharpMono 3.0.3032.29945")
        self.assertEqual(cc.SOURCE_SHA256,
                         "82ecc3fedf76af222dd13ad68258f3ae92146e9fad7dc6a4a96f3270fccf71fc")
        self.assertEqual(cc.SOURCE_LOCATION,
                         "PerformanceControl.cs:534-544; EngineControl.cs:924-933")
        self.assertIn("not an inflation-adjusted modern value", cc.SOURCE_SCOPE)

    def test_the_empirical_rates_are_the_recovered_ones(self):
        self.assertEqual(cc.LOAD_DISPLACEMENT_FRACTION, 0.02)
        self.assertEqual(cc.LIGHT_USD_PER_LONGTON, 0.00014)
        self.assertEqual(cc.MACHINERY_USD_PER_LONGTON, 0.00056)
        self.assertEqual(cc.BORNE_MULTIPLIER, 8.0)
        self.assertEqual(cc.BORNE_USD_PER_LONGTON, 0.00042)
        self.assertEqual(cc.DOLLARS_PER_POUND, 4.0)
        self.assertEqual(cc.YEAR_BOUNDARY, 1914)
        self.assertEqual(cc.YEAR_SPAN, 5.5)
        self.assertEqual(cc.YEAR_OFFSET, 1.5)

    def test_the_result_shape_is_the_documented_contract(self):
        result = cc.evaluate(SELECTED)
        self.assertEqual(sorted(result), ["currency_convention", "diagnostics", "inputs",
                                          "method_scope", "method_version", "provenance",
                                          "status", "values"])
        self.assertEqual(result["method_version"], cc.METHOD_VERSION)
        self.assertEqual(result["status"], "available")
        for key in ("usd_million", "gbp_million", "load_long_tons", "light_basis_long_tons",
                    "year_factor", "light_usd_million", "machinery_usd_million",
                    "borne_usd_million"):
            self.assertIn(key, result["values"]), key
        for key in ("displacement_t", "hull_year", "machinery_mass_t", "ammunition_mass_t",
                    "fuel_mass_t", "borne_mass_t"):
            self.assertIn(key, result["inputs"]), key

    def test_money_is_a_reading_and_never_a_weight(self):
        # There is no ledger target, no mass model and no adoption path in this
        # module at all: a reading that could be weighed would be a second,
        # undeclared method.
        exported = {name for name in dir(cc) if not name.startswith("_")}
        for forbidden in ("model", "estimate", "register", "adopt", "propose"):
            self.assertFalse([name for name in exported if forbidden in name.lower()],
                             forbidden)
        self.assertIn("SELECTED", cc.ASSUMPTIONS[0])


