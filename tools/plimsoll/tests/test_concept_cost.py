"""The recovered empirical cost reading: selected masses, historical currency.

Every expected number in this file comes from ``reference_cost`` below, a
longhand transcription of the recovered ``PerformanceControl.cs``/``EngineControl.cs``
expressions written without the module under test, or from arithmetic written out
in the test itself.

Nothing here is generated by the module under test, and nothing here claims a
modern price, a live exchange rate, an inflation-adjusted value or a figure about
any real ship or contract.
"""

import json
import math
from pathlib import Path
import sys
import unittest

HERE = Path(__file__).resolve().parent
PKG = HERE.parent
if str(PKG) not in sys.path:
    sys.path.insert(0, str(PKG))

import concept_cost as cc  # noqa: E402

VECTORS = json.loads((HERE / "fixtures/concept/original-fixed-armour-cost-vectors.json")
                     .read_text(encoding="utf-8"))
COST_ROWS = VECTORS["cost"]

LONG_TON_KG = 1016.0469088
LOAD_FRACTION = 0.02
LIGHT_RATE = 0.00014
MACHINERY_RATE = 0.00056
BORNE_MULTIPLIER = 8.0
BORNE_RATE = 0.00042
DOLLARS_PER_POUND = 4.0
YEAR_BOUNDARY = 1914
YEAR_SPAN = 5.5
YEAR_OFFSET = 1.5

DISPLACEMENT_T = 8200.0
HULL_YEAR = 1913
MACHINERY_T = 1168.4539
AMMUNITION_T = 45.7221
FUEL_T = 711.2328
BORNE_T = 122.0

SELECTED = {
    "displacement_t": DISPLACEMENT_T,
    "hull_year": HULL_YEAR,
    "machinery_mass_t": MACHINERY_T,
    "ammunition_mass_t": AMMUNITION_T,
    "fuel_mass_t": FUEL_T,
    "borne_mass_t": BORNE_T,
}


def _lt(tonnes):
    return tonnes * 1000.0 / LONG_TON_KG


def reference_year_factor(year):
    """PerformanceControl.cs:537-539, transcribed verbatim."""
    if year + 2 > YEAR_BOUNDARY:
        return 1.0 + (year + YEAR_OFFSET - float(YEAR_BOUNDARY)) / YEAR_SPAN
    return 1.0


# PerformanceControl.cs:534-544 with EngineControl.cs:926, transcribed verbatim.
def reference_cost(displacement_t, machinery_t, ammunition_t, fuel_t, borne_t, year):
    displacement_lt = _lt(displacement_t)
    load_lt = displacement_lt * LOAD_FRACTION + _lt(ammunition_t) + _lt(fuel_t)
    light_lt = displacement_lt - load_lt
    light_usd = light_lt * LIGHT_RATE
    machinery_usd = _lt(machinery_t) * MACHINERY_RATE
    borne_usd = (_lt(borne_t) * BORNE_MULTIPLIER) * BORNE_RATE
    base_usd = light_usd + machinery_usd + borne_usd
    factor = reference_year_factor(year)
    usd = base_usd * factor
    return {"usd_million": usd, "gbp_million": usd / DOLLARS_PER_POUND,
            "base_usd_million": base_usd, "load_long_tons": load_lt,
            "light_basis_long_tons": light_lt, "year_factor": factor,
            "light_usd_million": light_usd, "machinery_usd_million": machinery_usd,
            "borne_usd_million": borne_usd}


def close(actual, expected, tolerance=1e-12):
    if expected == 0:
        return abs(actual) <= tolerance
    return abs(actual - expected) <= tolerance * abs(expected)


