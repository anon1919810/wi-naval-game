class OriginalAssemblyVectorTests(unittest.TestCase):
    """Every supported recovered cost reading, against the original assembly.

    Unlike everything else in this file, no row was transcribed from the recovered
    C#. Each was produced by invoking ``EngineControl.loadWeightCalc`` and then
    ``PerformanceControl.costCalc`` directly on the recovered binary, and the
    curated fixture records only what the original received, what it returned and
    which binary and method identity it came from.

    The original's own intermediates are ``float``; this module is ``float64``.
    The stated tolerance is the fixture's ``relative_tolerance``.
    """

    def test_the_fixture_carries_the_binary_and_method_provenance(self):
        original = VECTORS["original_binary"]
        self.assertEqual(original["sha256"], cc.SOURCE_SHA256)
        self.assertTrue(original["sha256_matches"])
        self.assertEqual(VECTORS["method_identities"]["cost"], cc.METHOD_VERSION)
        self.assertEqual(VECTORS["original_convention"]["INCH"], 0.0185)
        self.assertEqual(VECTORS["coverage"]["cost_supported_cases"], len(COST_ROWS))
        self.assertEqual(sorted({row["in"]["hull_year"] for row in COST_ROWS}),
                         sorted(VECTORS["coverage"]["cost_years_covered"]))

    def test_every_supported_original_cost_reading_is_reproduced(self):
        tolerance = VECTORS["relative_tolerance"]
        worst, worst_id = 0.0, None
        for row in COST_ROWS:
            values = cc.evaluate(row["in"])["values"]
            for field, expected in row["out"].items():
                with self.subTest(case=row["id"], field=field):
                    actual = values[field]
                    self.assertIsNotNone(actual)
                    relative = abs(actual - expected) / max(abs(expected), 1e-9)
                    if relative > worst:
                        worst, worst_id = relative, "%s/%s" % (row["id"], field)
                    self.assertLessEqual(relative, tolerance)
        self.assertIsNotNone(worst_id)

    def test_the_two_impossible_rows_are_refused_even_though_the_original_priced_them(self):
        # The original computed a price from a NEGATIVE light basis on these two
        # rows because the load exceeds the displacement. This project reports them
        # unavailable instead: an impossible basis never becomes a plausible price,
        # and the original's number is kept in the fixture as the disagreement.
        guarded = VECTORS["cost_guarded"]["rows"]
        self.assertEqual({row["id"] for row in guarded},
                         {"F8b_1912_heavy_ammo_fuel", "F8c_1912_disp50"})
        for row in guarded:
            with self.subTest(case=row["id"]):
                self.assertLess(row["out"]["light_basis_long_tons"], 0.0)
                self.assertGreater(row["out"]["load_long_tons"],
                                   row["in"]["displacement_t"] * 1000.0 / LONG_TON_KG)
                result = cc.evaluate(row["in"])
                self.assertEqual(result["status"], "unavailable")
                self.assertIsNone(result["values"]["usd_million"])
                self.assertIsNone(result["values"]["gbp_million"])
                self.assertIsNone(result["values"]["load_long_tons"])
                self.assertTrue(any("negative" in d["message"] for d in result["diagnostics"]))
                # The guarded rows are excluded from the numeric parity set.
                self.assertNotIn(row["id"], {entry["id"] for entry in COST_ROWS})

    def test_the_recorded_unsupported_boundaries_are_not_priced(self):
        guarded = {row["id"] for row in VECTORS["cost_guarded"]["rows"]}
        for case_id in VECTORS["unsupported_boundary"]["cost_case_ids"]:
            with self.subTest(case=case_id):
                self.assertNotIn(case_id, {row["id"] for row in COST_ROWS} | guarded)

    def test_the_year_branch_boundary_is_covered_by_the_original_sweep(self):
        years = {row["in"]["hull_year"]: set() for row in COST_ROWS}
        for row in COST_ROWS:
            years[row["in"]["hull_year"]].add(round(row["out"]["year_factor"], 6))
        self.assertEqual(years[1911], {1.0})
        self.assertEqual(years[1912], {1.0})
        self.assertGreater(min(years[1913]), 1.0)


