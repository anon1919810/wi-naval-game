class CostReadingTests(unittest.TestCase):

    def test_the_recovered_expression_is_reproduced_value_for_value(self):
        result = cc.evaluate(SELECTED)
        expected = reference_cost(DISPLACEMENT_T, MACHINERY_T, AMMUNITION_T, FUEL_T,
                                  BORNE_T, HULL_YEAR)
        self.assertEqual(result["status"], "available")
        for key, value in expected.items():
            self.assertTrue(close(result["values"][key], value), key)

    def test_the_load_is_two_percent_plus_the_selected_magazine_and_bunker(self):
        result = cc.evaluate(SELECTED)
        load = (_lt(DISPLACEMENT_T) * 0.02 + _lt(AMMUNITION_T) + _lt(FUEL_T))
        self.assertTrue(close(result["values"]["load_long_tons"], load))
        self.assertTrue(close(result["values"]["light_basis_long_tons"],
                              _lt(DISPLACEMENT_T) - load))

    def test_the_three_contributions_sum_to_the_unadjusted_base(self):
        result = cc.evaluate(SELECTED)
        values = result["values"]
        self.assertTrue(close(values["light_usd_million"] + values["machinery_usd_million"]
                              + values["borne_usd_million"], values["base_usd_million"]))

    def test_the_borne_term_is_the_selected_bare_gun_mass_times_eight(self):
        base = dict(SELECTED, hull_year=1900)
        result = cc.evaluate(base)
        self.assertTrue(close(result["values"]["borne_usd_million"],
                              _lt(BORNE_T) * 8.0 * 0.00042))

    def test_the_pound_reading_is_the_source_own_fixed_four_to_one_division(self):
        result = cc.evaluate(SELECTED)
        self.assertTrue(close(result["values"]["gbp_million"],
                              result["values"]["usd_million"] / 4.0))
        self.assertIn("4:1", result["currency_convention"])
        self.assertIn("rather than a live exchange rate", result["currency_convention"])

    def test_every_reported_input_is_a_flat_scalar(self):
        result = cc.evaluate(SELECTED)
        for key, value in result["inputs"].items():
            self.assertIsInstance(value, (int, float), key)
            self.assertFalse(isinstance(value, bool), key)
            self.assertTrue(math.isfinite(value), key)

    def test_the_conversions_are_reported_beside_the_canonical_tonnes(self):
        result = cc.evaluate(SELECTED)
        self.assertTrue(close(result["inputs"]["displacement_long_tons"],
                              _lt(DISPLACEMENT_T)))
        self.assertTrue(close(result["inputs"]["machinery_long_tons"], _lt(MACHINERY_T)))
        self.assertTrue(close(result["inputs"]["borne_long_tons"], _lt(BORNE_T)))
        self.assertTrue(close(result["inputs"]["load_long_tons"],
                              result["values"]["load_long_tons"]))

    def test_the_result_is_json_serializable_and_finite(self):
        result = cc.evaluate(SELECTED)
        json.dumps(result, allow_nan=False)


class YearBranchTests(unittest.TestCase):

    def test_the_source_float32_branch_boundary_is_exactly_between_1912_and_1913(self):
        # `hull_year + 2 > 1914` is false for 1912 and true for 1913.
        self.assertEqual(cc.evaluate(dict(SELECTED, hull_year=1912))["values"]["year_factor"],
                         1.0)
        self.assertEqual(cc.evaluate(dict(SELECTED, hull_year=1913))["values"]["year_factor"],
                         1.0 + 0.5 / 5.5)
        self.assertTrue(close(cc.evaluate(dict(SELECTED, hull_year=1913))
                              ["values"]["year_factor"], reference_year_factor(1913)))

    def test_every_year_on_both_sides_of_the_boundary_matches_the_transcription(self):
        for year in (1850, 1900, 1910, 1911, 1912, 1913, 1914, 1920, 1950):
            with self.subTest(year=year):
                values = cc.evaluate(dict(SELECTED, hull_year=year))["values"]
                self.assertTrue(close(values["year_factor"], reference_year_factor(year)))
                if year + 2 <= 1914:
                    self.assertEqual(values["year_factor"], 1.0)

    def test_a_fractional_hull_year_is_refused_rather_than_truncated(self):
        result = cc.evaluate(dict(SELECTED, hull_year=1912.5))
        self.assertEqual(result["status"], "unavailable")
        self.assertIsNone(result["values"]["usd_million"])
        self.assertTrue(any("whole hull years" in d["message"] for d in result["diagnostics"]))

    def test_an_unsupported_hull_year_cannot_become_a_price(self):
        for year in (1849, 1951, 3000):
            with self.subTest(year=year):
                result = cc.evaluate(dict(SELECTED, hull_year=year))
                self.assertEqual(result["status"], "unavailable")
                self.assertIsNone(result["values"]["usd_million"])


class UnknownAndDomainTests(unittest.TestCase):

    def test_an_absent_fact_is_unknown_and_never_read_as_zero(self):
        for field in cc.INPUT_FIELDS:
            with self.subTest(missing=field):
                inputs = {key: value for key, value in SELECTED.items() if key != field}
                result = cc.evaluate(inputs)
                self.assertEqual(result["status"], "unavailable")
                self.assertIsNone(result["values"]["usd_million"])
                self.assertTrue(result["diagnostics"])

    def test_a_non_finite_or_wrongly_typed_fact_is_unknown(self):
        for value in (float("nan"), float("inf"), "8200", True, [8200.0]):
            with self.subTest(value=value):
                result = cc.evaluate(dict(SELECTED, displacement_t=value))
                self.assertEqual(result["status"], "unavailable")
                self.assertIsNone(result["values"]["usd_million"])

    def test_an_explicitly_allocated_empty_role_is_a_determined_zero(self):
        result = cc.evaluate(dict(SELECTED, ammunition_mass_t=0.0, fuel_mass_t=0.0,
                                 borne_mass_t=0.0))
        self.assertEqual(result["status"], "available")
        self.assertTrue(close(result["values"]["borne_usd_million"], 0.0))
        self.assertTrue(close(result["values"]["load_long_tons"],
                              _lt(DISPLACEMENT_T) * 0.02))

    def test_a_non_positive_displacement_is_not_a_zero_price(self):
        for displacement in (0.0, -8200.0):
            with self.subTest(displacement=displacement):
                result = cc.evaluate(dict(SELECTED, displacement_t=displacement))
                self.assertEqual(result["status"], "unavailable")
                self.assertIsNone(result["values"]["usd_million"])
                self.assertTrue(any("not positive" in d["message"] or "negative" in d["message"]
                                    for d in result["diagnostics"]))
        zero = cc.evaluate(dict(SELECTED, displacement_t=0.0))
        self.assertTrue(any("not positive" in d["message"] for d in zero["diagnostics"]))

    def test_an_impossible_negative_light_basis_is_reported_and_never_clamped(self):
        # A fuel load far above the displacement would drive the light basis
        # negative, which the recovered expression cannot mean.
        result = cc.evaluate(dict(SELECTED, displacement_t=100.0, fuel_mass_t=90000.0,
                                 ammunition_mass_t=9000.0))
        self.assertEqual(result["status"], "unavailable")
        self.assertIsNone(result["values"]["usd_million"])
        self.assertTrue(any("negative" in d["message"] for d in result["diagnostics"]))

    def test_a_negative_selected_mass_is_refused(self):
        result = cc.evaluate(dict(SELECTED, machinery_mass_t=-1.0))
        self.assertEqual(result["status"], "unavailable")
        self.assertTrue(any("negative" in d["message"] for d in result["diagnostics"]))

    def test_an_overflow_cannot_become_a_plausible_zero_price(self):
        result = cc.evaluate(dict(SELECTED, displacement_t=1e308, machinery_mass_t=1e308,
                                 ammunition_mass_t=1e308, fuel_mass_t=1e308,
                                 borne_mass_t=1e308))
        self.assertEqual(result["status"], "unavailable")
        self.assertIsNone(result["values"]["usd_million"])


