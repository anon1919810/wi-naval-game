"""Independent flat-panel armour geometry kernel (``plimsoll-armour-panels-v1``).

Every expected number here is either arithmetic written out longhand in the test
(area = L x W x count, volume = area x thickness_mm / 1000, mass = volume x
density / 1000) or the spec's own hand anchor. Nothing is generated by the
module under test.
"""

