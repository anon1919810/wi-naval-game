class Boundaries(unittest.TestCase):
    def test_extreme_developed_values_are_finite(self):
        raw = plate(length_m=5000.0, width_m=5000.0, thickness_mm=2000.0,
                    density_kg_m3=30000.0, count=1000000,
                    width_basis="developed")
        root, region_norm = normalized_region(region(plates=[raw]))
        result = ag.evaluate(region_norm, "belt_main", source=root["source"])
        self.assertEqual(result["values"]["area_m2"], 5000.0 * 5000.0 * 1000000)
        self.assertAlmostEqual(result["values"]["volume_m3"],
                               5000.0 * 5000.0 * 1000000 * 2000.0 / 1000.0)
        json.dumps(result, allow_nan=False)

    def test_extreme_angle_boundaries_accepted(self):
        for angle in (-89.0, 89.0):
            raw = plate(width_basis="projected", inclination_deg=angle)
            root, region_norm = normalized_region(region(plates=[raw]))
            self.assertEqual(region_norm["plates"][0]["inclination_deg"], angle)
            result = ag.evaluate(region_norm, "belt_main", source=root["source"])
            json.dumps(result, allow_nan=False)
            self.assertGreater(result["values"]["area_m2"], 40.0)

    def test_zero_extent_with_tiny_positive_density(self):
        raw = plate(length_m=0.0, width_m=0.0, thickness_mm=0.0,
                    density_kg_m3=0.001, count=0)
        root, region_norm = normalized_region(region(plates=[raw]))
        result = ag.evaluate(region_norm, "belt_main", source=root["source"])
        self.assertEqual(result["values"]["mass_t"], 0.0)

    def test_result_is_finite_json(self):
        root, region_norm = normalized_region(region())
        result = ag.evaluate(region_norm, "belt_main", source=root["source"])
        json.dumps(result, allow_nan=False)


class StructuralRejections(unittest.TestCase):
    def assert_rejected(self, geometry, fixed=FIXED):
        with self.assertRaises(ag.ArmourGeometryError) as ctx:
            ag.normalize(as_root(geometry), fixed)
        diagnostics = ctx.exception.diagnostics
        self.assertTrue(diagnostics)
        for entry in diagnostics:
            self.assertEqual(set(entry), DIAG_KEYS)
            self.assertTrue(entry["blocking"])
        return diagnostics

    def test_numeric_domain_rejections(self):
        cases = {
            "negative length": plate(length_m=-1.0),
            "length exceeds float range even for zero count": plate(length_m=10**400, count=0),
            "thickness too big": plate(thickness_mm=2001.0),
            "density too big": plate(density_kg_m3=30001.0),
            "density zero": plate(density_kg_m3=0.0),
            "count too big": plate(count=1000001),
            "count fractional": plate(count=1.5),
            "count bool": plate(count=True),
            "angle too big": plate(inclination_deg=90.0, width_basis="projected"),
            "angle too small": plate(inclination_deg=-90.0, width_basis="projected"),
            "angle bool": plate(inclination_deg=True, width_basis="projected"),
            "length nonfinite": plate(length_m=float("nan")),
            "width infinite": plate(width_m=float("inf")),
        }
        for name, raw in cases.items():
            with self.subTest(name):
                self.assert_rejected({"source": "s", "regions": [region(plates=[raw])]})

    def test_structural_rejections(self):
        good = region()
        cases = {
            "unknown plate key": {"source": "s", "regions": [
                region(plates=[plate(extra=1)])]},
            "unknown region key": {"source": "s", "regions": [
                dict(good, extra=1)]},
            "unknown root key": {"source": "s", "regions": [good], "extra": 1},
            "source wrong type": {"source": "s", "regions": [
                region(plates=[plate(source=5)])]},
            "bad plate id": {"source": "s", "regions": [
                region(plates=[plate(id="bad id")])]},
            "bad basis": {"source": "s", "regions": [
                region(plates=[plate(width_basis="flat")])]},
            "unknown fixed id": {"source": "s", "regions": [
                region(fixed_armour_id="missing-1")]},
            "ineligible bulge": {"source": "s", "regions": [
                region(fixed_armour_id="bulge-1")]},
            "ineligible conning": {"source": "s", "regions": [
                region(fixed_armour_id="conning-1")]},
            "missing fixed id": {"source": "s", "regions": [
                {"source": "r", "plates": [plate()]}]},
            "duplicate plate id": {"source": "s", "regions": [
                region(plates=[plate(id="p1"), plate(id="p1")])]},
            "regions wrong type": {"source": "s", "regions": "nope"},
            "region wrong type": {"source": "s", "regions": ["nope"]},
            "plate wrong type": {"source": "s", "regions": [region(plates=[42])]},
        }
        for name, geometry in cases.items():
            with self.subTest(name):
                self.assert_rejected(geometry)

    def test_fixed_id_grammar_also_applies_to_a_supplied_reference_map(self):
        raw = {"source": "s", "regions": [dict(region(), fixed_armour_id="bad id")]}
        with self.assertRaises(ag.ArmourGeometryError):
            ag.normalize(raw, [{"id": "bad id", "kind": "belt_main"}])

    def test_duplicate_fixed_id_across_regions(self):
        geometry = {"source": "s", "regions": [
            region(fixed_armour_id="belt-1"),
            region(fixed_armour_id="belt-1"),
        ]}
        diagnostics = self.assert_rejected(geometry)
        self.assertTrue(any(d["code"] == "armour_geometry.duplicate_id"
                            for d in diagnostics))

    def test_too_many_regions_and_plates(self):
        many_regions = {"source": "s", "regions": [
            region(fixed_armour_id="belt-1") for _ in range(51)]}
        self.assert_rejected(many_regions)
        many_plates = {"source": "s", "regions": [
            region(plates=[plate(id="p%d" % i) for i in range(101)])]}
        self.assert_rejected(many_plates)

    def test_diagnostic_codes_are_specific(self):
        diagnostics = self.assert_rejected({"source": "s", "regions": [
            region(fixed_armour_id="missing-1")]})
        self.assertEqual(diagnostics[0]["code"], "armour_geometry.reference_unknown")
        self.assertEqual(diagnostics[0]["severity"], "error")


class RootContractRegressions(unittest.TestCase):
    """The two bounded contract fixes: root-only normalize, mass-based adoption."""

    def test_invalid_root_type_and_unknown_key_are_rejected(self):
        for bad in (42, "root", [], {"regions": [], "unknown": 1}):
            with self.subTest(bad=bad):
                with self.assertRaises(ag.ArmourGeometryError) as ctx:
                    ag.normalize(bad, FIXED)
                for entry in ctx.exception.diagnostics:
                    self.assertEqual(set(entry), DIAG_KEYS)
                    self.assertTrue(entry["blocking"])

    def test_source_only_draft_is_preserved_not_lost(self):
        # A draft that names a source before any region is declared must survive
        # normalization rather than being silently read as absent.
        self.assertEqual(ag.normalize({"source": "draft-7"}, FIXED),
                         {"source": "draft-7", "regions": []})

    def test_zero_thickness_unknown_area_is_adoptable_when_mass_zero(self):
        raw = plate(thickness_mm=0.0, density_kg_m3=None, length_m=None,
                    width_m=None, width_basis="developed")
        root_value, region_norm = normalized_region(region(plates=[raw]))
        result = ag.evaluate(region_norm, "belt_main", source=root_value["source"])
        self.assertEqual(result["records"][0]["values"]["mass_t"], 0.0)
        self.assertIsNone(result["records"][0]["values"]["area_m2"])
        self.assertEqual(result["records"][0]["status"], "partial")
        self.assertTrue(result["records"][0]["adoptable"])
        self.assertTrue(result["adoptable"])
        self.assertEqual(result["status"], "partial")

    def test_unknown_mass_plate_is_not_adoptable(self):
        raw = plate(count=None, length_m=None, width_m=None, thickness_mm=None,
                    density_kg_m3=None, width_basis=None)
        root_value, region_norm = normalized_region(region(plates=[raw]))
        result = ag.evaluate(region_norm, "belt_main", source=root_value["source"])
        self.assertFalse(result["records"][0]["adoptable"])
        self.assertFalse(result["adoptable"])

    def test_evaluate_refuses_curved_kinds(self):
        for kind in ("bulge", "conning"):
            with self.subTest(kind=kind):
                with self.assertRaises(ag.ArmourGeometryError):
                    ag.evaluate(region(), kind, source="drawing-42")


class Purity(unittest.TestCase):
    def test_normalize_and_evaluate_do_not_mutate_inputs(self):
        raw_region = region()
        geometry = {"source": "drawing-42", "regions": [raw_region]}
        whole = as_root(geometry)
        snapshot_whole = copy.deepcopy(whole)
        fixed_snapshot = copy.deepcopy(FIXED)

        root = ag.normalize(whole, FIXED)
        self.assertEqual(whole, snapshot_whole)
        self.assertEqual(FIXED, fixed_snapshot)

        region_snapshot = copy.deepcopy(root["regions"][0])
        ag.evaluate(root["regions"][0], "belt_main", source=root["source"])
        self.assertEqual(root["regions"][0], region_snapshot)


