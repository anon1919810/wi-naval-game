import armour_geometry as ag  # noqa: E402

DPATH = "$.concept_design.armour_geometry"

FIXED = [
    {"id": "belt-1", "kind": "belt_main"},
    {"id": "ends-1", "kind": "belt_ends"},
    {"id": "upper-1", "kind": "belt_upper"},
    {"id": "bulk-1", "kind": "bulkhead"},
    {"id": "deck-1", "kind": "deck"},
    {"id": "bulge-1", "kind": "bulge"},
    {"id": "conning-1", "kind": "conning"},
]

DIAG_KEYS = {"severity", "code", "path", "message", "blocking"}


def as_root(geometry):
    # normalize() is handed the geometry root itself, never a project wrapper.
    return geometry


def plate(**kw):
    base = {"id": "p1", "source": "plate-src", "density_source": "mat-src",
            "length_m": 10.0, "width_m": 2.0, "thickness_mm": 100.0,
            "density_kg_m3": 7850.0, "count": 2, "width_basis": "developed",
            "inclination_deg": None}
    base.update(kw)
    return base


def region(**kw):
    base = {"fixed_armour_id": "belt-1", "source": "region-src",
            "plates": [plate()]}
    base.update(kw)
    return base


def normalized_region(region_dict, source="drawing-42", fixed=FIXED):
    geometry = {"source": source, "regions": [region_dict]}
    root = ag.normalize(as_root(geometry), fixed)
    return root, root["regions"][0]


class AbsentAndNull(unittest.TestCase):
    def test_null_returns_none(self):
        self.assertIsNone(ag.normalize(None, FIXED))

    def test_missing_regions_normalize_to_empty_list(self):
        root = ag.normalize(as_root({"source": "drawing-42"}), FIXED)
        self.assertEqual(root, {"source": "drawing-42", "regions": []})
        root = ag.normalize(as_root({"source": None, "regions": []}), FIXED)
        self.assertEqual(root, {"source": None, "regions": []})

    def test_unknown_numeric_fields_normalize_to_none(self):
        raw = plate(length_m=None, width_m=None, thickness_mm=None,
                    density_kg_m3=None, count=None, width_basis=None,
                    inclination_deg=None, source=None, density_source=None)
        root, region_norm = normalized_region(region(plates=[raw]))
        kept = region_norm["plates"][0]
        for field in ("length_m", "width_m", "thickness_mm", "density_kg_m3",
                      "count", "width_basis", "inclination_deg", "source",
                      "density_source"):
            self.assertIsNone(kept[field], field)
        result = ag.evaluate(region_norm, "belt_main", source=root["source"])
        self.assertEqual(result["status"], "unavailable")


class HandAnchors(unittest.TestCase):
    def test_developed_belt_anchor(self):
        root, region_norm = normalized_region(region())
        result = ag.evaluate(region_norm, "belt_main", source=root["source"])
        self.assertEqual(result["id"], "belt-1")
        self.assertEqual(result["method_version"], ag.METHOD_VERSION)
        self.assertEqual(result["status"], "available")
        self.assertTrue(result["adoptable"])
        self.assertEqual(result["values"]["area_m2"], 40.0)
        self.assertEqual(result["values"]["volume_m3"], 4.0)
        self.assertEqual(result["values"]["mass_t"], 31.4)
        self.assertEqual(result["values"]["known_mass_subtotal_t"], 31.4)
        record = result["records"][0]
        self.assertEqual(record["id"], "p1")
        self.assertEqual(record["method_version"], ag.METHOD_VERSION)
        self.assertEqual(record["status"], "available")
        self.assertTrue(record["adoptable"])
        self.assertEqual(record["values"], {"area_m2": 40.0, "volume_m3": 4.0,
                                            "mass_t": 31.4})

    def test_projected_belt_anchor_both_signs(self):
        for angle, signed in ((60.0, 60.0), (-60.0, -60.0)):
            raw = plate(width_basis="projected", inclination_deg=signed)
            root, region_norm = normalized_region(region(plates=[raw]))
            result = ag.evaluate(region_norm, "belt_main", source=root["source"])
            self.assertAlmostEqual(result["values"]["area_m2"], 80.0, places=6)
            self.assertAlmostEqual(result["values"]["volume_m3"], 8.0, places=6)
            self.assertAlmostEqual(result["values"]["mass_t"], 62.8, places=6)
            self.assertTrue(result["adoptable"])

    def test_developed_basis_ignores_angle(self):
        raw = plate(width_basis="developed", inclination_deg=60.0)
        root, region_norm = normalized_region(region(plates=[raw]))
        result = ag.evaluate(region_norm, "belt_main", source=root["source"])
        self.assertEqual(result["values"]["area_m2"], 40.0)
        self.assertEqual(result["values"]["mass_t"], 31.4)

    def test_layered_deck_anchor(self):
        plates = [
            plate(id="layer-1", thickness_mm=50.0, length_m=20.0, width_m=8.0,
                  count=1),
            plate(id="layer-2", thickness_mm=25.0, length_m=20.0, width_m=8.0,
                  count=1),
        ]
        root, region_norm = normalized_region(
            region(fixed_armour_id="deck-1", plates=plates))
        result = ag.evaluate(region_norm, "deck", source=root["source"])
        self.assertEqual(result["values"]["area_m2"], 320.0)
        self.assertEqual(result["values"]["volume_m3"], 12.0)
        # Each declared layer contributes once (62.8 t + 31.4 t); the region
        # mass sums those readings rather than recomputing from a merged volume.
        self.assertAlmostEqual(result["values"]["mass_t"], 94.2, places=6)
        self.assertEqual(len(result["records"]), 2)
        self.assertEqual(result["provenance"]["width_angle_convention"],
                         "from_horizontal")
        self.assertTrue(result["adoptable"])

    def test_belt_angle_convention_is_from_vertical(self):
        root, region_norm = normalized_region(region())
        result = ag.evaluate(region_norm, "belt_main", source=root["source"])
        self.assertEqual(result["provenance"]["width_angle_convention"],
                         "from_vertical")
        self.assertEqual(result["records"][0]["provenance"]["width_angle_convention"],
                         "from_vertical")


class KnownZeroBehaviour(unittest.TestCase):
    def test_zero_count_is_determined_zero_without_dimensions(self):
        raw = plate(count=0, length_m=None, width_m=None, thickness_mm=None,
                    density_kg_m3=None, width_basis=None, inclination_deg=None,
                    source=None, density_source=None)
        root, region_norm = normalized_region(region(plates=[raw]))
        result = ag.evaluate(region_norm, "belt_main", source=root["source"])
        self.assertEqual(result["status"], "available")
        self.assertEqual(result["values"], {"area_m2": 0.0, "volume_m3": 0.0,
                                            "mass_t": 0.0,
                                            "known_mass_subtotal_t": 0.0})
        self.assertTrue(result["adoptable"])
        self.assertTrue(result["records"][0]["adoptable"])

    def test_zero_thickness_determines_mass_while_area_unknown(self):
        raw = plate(thickness_mm=0.0, density_kg_m3=None, length_m=None,
                    width_m=None, width_basis="developed")
        root, region_norm = normalized_region(region(plates=[raw]))
        result = ag.evaluate(region_norm, "belt_main", source=root["source"])
        record = result["records"][0]
        self.assertEqual(record["status"], "partial")
        self.assertIsNone(record["values"]["area_m2"])
        self.assertEqual(record["values"]["volume_m3"], 0.0)
        self.assertEqual(record["values"]["mass_t"], 0.0)
        self.assertIsNone(result["values"]["area_m2"])
        self.assertEqual(result["values"]["volume_m3"], 0.0)
        self.assertEqual(result["values"]["mass_t"], 0.0)
        # A determined zero mass is adoptable even though the area is unknown.
        self.assertTrue(result["adoptable"])


class IncompleteRegions(unittest.TestCase):
    def test_unknown_plate_blocks_complete_mass_but_keeps_subtotal(self):
        plates = [plate(id="known"), plate(id="unknown", count=None,
                                           length_m=None, width_m=None,
                                           thickness_mm=None, density_kg_m3=None,
                                           width_basis=None)]
