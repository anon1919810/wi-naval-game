"""Whole-battery gun, mount and layout-armour totals kernel.

Every expected number in this file comes from one of two independent places:

* ``fixtures/concept/original-battery-totals-vectors.json``, a curated extraction
  of the original assembly's own ``mountsCalc``/``gunWeightCalc`` readings (see
  its ``scope``/``source_sha256``/``counts`` fields), reconstructed through the
  concept two-group model;
* arithmetic written out in the test itself, such as the spec's mount-count
  weighted hand sample ``(2 x 0.75 + 1) / 3``.

Nothing here is generated by the module under test, and nothing here claims
whole-program parity: the per-row gun, mount and ammunition estimates stay
``sps-3b3-adapted-v1`` and the layout freeboard, height factor and mixed armour
stay ``sps-3b3-battery-layout-v1``.
"""

import json
import math
from pathlib import Path
import sys
import unittest

HERE = Path(__file__).resolve().parent
PKG = HERE.parent
if str(PKG) not in sys.path:
    sys.path.insert(0, str(PKG))

import battery_layout as bl  # noqa: E402
import battery_totals as bt  # noqa: E402
import concept_estimates as ce  # noqa: E402

FIXTURE = json.loads((HERE / "fixtures/concept/original-battery-totals-vectors.json")
                     .read_text(encoding="utf-8"))
M_PER_FT = ce.M_PER_FT
GUN_TYPES = FIXTURE["vocabulary"]["gun_types"]
MOUNT_TYPES = FIXTURE["vocabulary"]["mount_types"]


def relative(actual, expected):
    if expected == 0:
        return abs(actual)
    return abs(actual - expected) / abs(expected)


def feet_to_m(value):
    return round(value * M_PER_FT, 9)


def batteries_from_row(row):
    """Two normalized battery rows that a fixture row can reference."""
    common = {"calibre_mm": row["calibre_mm"], "year": row["year"],
              "barrel_calibres": row["barrel_calibres"],
              "gun_type": GUN_TYPES[row["gun_type_index"]],
              "mount_type": MOUNT_TYPES[row["mount_type_index"]]}
    rows = []
    for name in ("group1", "group2"):
        group = row[name]
        rows.append(dict(common, id="main_g%s" % name[-1],
                         mount_count=(group["elevated_mounts"] + group["deck_mounts"]
                                      + group["depressed_mounts"]),
                         barrels_per_mount=group["per_mount"],
                         shared_cradle=group["shared_cradle"]))
    return rows


def layout_from_row(row, **overrides):
    """One layout declaration that reproduces an original ``mountsCalc`` case."""
    profile = {"forecastle_fraction": row["deck_profile"]["forecastle_fraction"],
               "forward_deck_fraction": row["deck_profile"]["forward_deck_fraction"],
               "forward_fore_m": feet_to_m(row["deck_profile"]["forward_fore_ft"]),
               "forward_aft_m": feet_to_m(row["deck_profile"]["forward_aft_ft"]),
               "aft_fore_m": feet_to_m(row["deck_profile"]["aft_fore_ft"]),
               "aft_aft_m": feet_to_m(row["deck_profile"]["aft_aft_ft"])}
    layout = {
        "id": "case-%s" % (row["case_id"].lower(),),
        "source": "original assembly reading %s" % row["case_id"],
        "group1": {"battery_id": "main_g1", "mount_selector": row["group1"]["selector"],
                   "layout_index": row["group1"]["layout_index"],
                   "elevated_mounts": row["group1"]["elevated_mounts"],
                   "deck_mounts": row["group1"]["deck_mounts"],
                   "depressed_mounts": row["group1"]["depressed_mounts"]},
        "group2": {"battery_id": "main_g2", "mount_selector": row["group2"]["selector"],
                   "layout_index": row["group2"]["layout_index"],
                   "elevated_mounts": row["group2"]["elevated_mounts"],
                   "deck_mounts": row["group2"]["deck_mounts"],
                   "depressed_mounts": row["group2"]["depressed_mounts"]},
        "group2_double_elevation": row["group2_double_elevation"],
        "group2_double_depression": row["group2_double_depression"],
        "deck_profile": profile,
        "armour": {"system_id": "weapons.main", "item_id": "weapons.layout_armour",
                   "face_mm": row["arm_mm"]["face"],
                   "rear_roof_mm": row["arm_mm"]["rear_roof"],
                   "barbette_mm": row["arm_mm"]["barbette"]},
    }
    for key, value in overrides.items():
        if value is _DELETE:
            layout.pop(key, None)
        elif isinstance(value, dict) and isinstance(layout.get(key), dict):
            layout[key] = dict(layout[key], **value)
        else:
            layout[key] = value
    return layout


class _Delete:
    def __repr__(self):                                 # pragma: no cover - debugging aid
        return "<delete>"


_DELETE = _Delete()


def evaluate_row(row, **overrides):
    layout = layout_from_row(row, **overrides)
    batteries = batteries_from_row(row)
    validated = bl.validate_layouts([layout], batteries)[0]
    reading = bl.evaluate(validated, batteries)
    return bt.evaluate(layout, batteries, reading), reading, batteries


def synthetic_row(**overrides):
    """A minimal reconstructible fixture row used for hand-computed cases."""
    row = {
        "case_id": "hand", "family": "hand", "calibre_mm": 304.8, "calibre_in": 12.0,
        "barrel_calibres": 45, "year": 1910, "gun_type_index": 1, "mount_type_index": 3,
        "deck_profile": {"forecastle_fraction": 0.375, "forward_deck_fraction": 0.25,
                         "forward_fore_ft": 8.0, "forward_aft_ft": 7.0,
                         "aft_fore_ft": 6.0, "aft_aft_ft": 8.0},
        "group1": {"selector": 3, "layout_index": 0, "per_mount": 2, "shared_cradle": True,
                   "elevated_mounts": 2, "deck_mounts": 0, "depressed_mounts": 0},
        "group2": {"selector": 0, "layout_index": 7, "per_mount": 1, "shared_cradle": False,
                   "elevated_mounts": 1, "deck_mounts": 0, "depressed_mounts": 0},
        "group2_double_elevation": False, "group2_double_depression": False,
        "arm_mm": {"face": 254.0, "rear_roof": 127.0, "barbette": 152.4},
        "native_deck_g1": 0,
    }
    row.update(overrides)
    return row


class ModuleIdentityTests(unittest.TestCase):
    def test_the_kernel_carries_its_own_method_version(self):
        self.assertEqual(bt.METHOD_VERSION, "sps-3b3-battery-totals-v1")
        self.assertNotEqual(bt.METHOD_VERSION, ce.METHOD_VERSION)
        self.assertNotEqual(bt.METHOD_VERSION, bl.METHOD_VERSION)
        self.assertEqual(list(bt.VALUE_KEYS), ["guns_t", "mounts_t", "armour_t", "total_t"])

    def test_the_kernel_names_the_same_original_binary_without_inventing_one(self):
        self.assertEqual(bt.SOURCE_ASSEMBLY, ce.SOURCE_ASSEMBLY)
        self.assertEqual(bt.SOURCE_SHA256, ce.SOURCE_SHA256)
        self.assertEqual(bt.SOURCE_SHA256, bl.SOURCE_SHA256)
        self.assertEqual(FIXTURE["source_sha256"], ce.SOURCE_SHA256)
        self.assertEqual(FIXTURE["source_assembly"], ce.SOURCE_ASSEMBLY)
        for name, entry in FIXTURE["source_files"].items():
            self.assertRegex(entry["sha256"], r"\A[0-9a-f]{64}\Z", name)


class NativeAgreementTests(unittest.TestCase):
    """Whole-chain agreement with the original assembly's own readings."""

    def test_every_full_row_reproduces_the_native_gun_mount_armour_and_total(self):
        checked = 0
        worst = 0.0
        for row in FIXTURE["rows"]:
            with self.subTest(case=row["case_id"]):
                result, reading, _batteries = evaluate_row(row)
                native = row["native"]
                self.assertEqual(result["status"], "available", row["case_id"])
                values = result["values"]
                self.assertEqual(values["mounts"], native["mounts_g1"] + native["mounts_g2"])
                self.assertEqual(values["installed_guns"], native["barrels"])
                for key, want in (("guns_long_tons", native["gun_long_tons"]),
                                  ("mounts_long_tons", native["mount_long_tons"]),
                                  ("armour_long_tons", native["armour_long_tons"]),
                                  ("total_long_tons", native["total_long_tons"])):
                    error = relative(values[key], want)
                    worst = max(worst, error)
                    self.assertLess(error, 1e-5, (row["case_id"], key, values[key], want))
                # The tonne figures are the same reading through one conversion,
                # not a second independent estimate of the rounded native value.
                self.assertLess(relative(values["guns_t"], ce.long_tons_to_tonnes(
                    values["guns_long_tons"])), 1e-12)
                self.assertLess(relative(values["total_t"], ce.long_tons_to_tonnes(
                    values["total_long_tons"])), 1e-12)
                checked += 1
        self.assertGreaterEqual(checked, 600)
        self.assertLess(worst, 1e-5)

    def test_every_full_row_reproduces_the_mount_count_weighted_adjustment(self):
        checked = 0
        for row in FIXTURE["rows"]:
            with self.subTest(case=row["case_id"]):
                result, _reading, _batteries = evaluate_row(row)
                values = result["values"]
                self.assertIsNotNone(values["weight_adjustment"])
                weight = values["weight_adjustment"]
                mounts1 = row["native"]["mounts_g1"]
                mounts2 = row["native"]["mounts_g2"]
                if mounts1 + mounts2:
                    expected = ((bl.WEIGHT_ADJUSTMENT_BY_SELECTOR[row["group1"]["selector"]] * mounts1
                                 + bl.WEIGHT_ADJUSTMENT_BY_SELECTOR[row["group2"]["selector"]] * mounts2)
                                / float(mounts1 + mounts2))
                else:
                    expected = 1.0
                self.assertLess(relative(weight, expected), 1e-9)
                self.assertLess(relative(weight, row["native"]["weight_adjustment"]), 1e-5)
                checked += 1
        self.assertGreaterEqual(checked, 600)

    def test_every_weight_adjustment_only_row_reproduces_its_adjustment(self):
        checked = 0
        for row in FIXTURE["weight_adjustment_rows"]:
            with self.subTest(case=row["case_id"]):
                result, _reading, _batteries = evaluate_row(row)
                values = result["values"]
                self.assertLess(relative(values["weight_adjustment"],
                                         row["native"]["weight_adjustment"]), 1e-5)
                checked += 1
        self.assertGreaterEqual(checked, 100)

    def test_the_fixture_covers_the_selector_mixes_and_the_zero_groups(self):
        adjustments = set(FIXTURE["distinct_full_weight_adjustments"])
        self.assertIn(0.75, adjustments)
        self.assertIn(1.0, adjustments)
        self.assertIn(0.8333333, adjustments)
        zero = [row for row in FIXTURE["rows"]
                if row["native"]["mounts_g1"] == 0 and row["native"]["mounts_g2"] == 0]
        self.assertTrue(zero)
        single = [row for row in FIXTURE["rows"]
                  if (row["native"]["mounts_g1"] == 0) != (row["native"]["mounts_g2"] == 0)]
        self.assertTrue(single)
        excluded = "\n".join(entry["reason"] for entry in FIXTURE["excluded"])
        self.assertIn("negative group-1 deck slot", excluded)

    def test_a_zero_group_row_reports_a_determined_zero_total(self):
        zero = [row for row in FIXTURE["rows"]
                if row["native"]["mounts_g1"] == 0 and row["native"]["mounts_g2"] == 0]
        for row in zero:
            with self.subTest(case=row["case_id"]):
                result, _reading, _batteries = evaluate_row(row)
                values = result["values"]
                self.assertEqual(values["mounts"], 0)
                self.assertEqual(values["installed_guns"], 0)
                self.assertEqual(values["guns_long_tons"], 0.0)
                self.assertEqual(values["mounts_long_tons"], 0.0)
                self.assertEqual(values["total_long_tons"], 0.0)


class HandComputedTests(unittest.TestCase):
    """The spec's own hand sample, worked out here rather than imported."""

    def test_the_mount_count_weighted_hand_sample_is_two_times_zero_point_seven_five_plus_one_over_three(self):
        # Group 1: two mounts of a shared-cradle twin. Group 2: one single mount.
        # The recovered mountsCalc weights by MOUNT COUNT, so the whole-battery
        # adjustment is (2 x 0.75 + 1) / 3, not 0.8 and not a second x0.75.
        row = synthetic_row(
            group1={"selector": 3, "layout_index": 0, "per_mount": 2, "shared_cradle": True,
                    "elevated_mounts": 2, "deck_mounts": 0, "depressed_mounts": 0},
            group2={"selector": 0, "layout_index": 7, "per_mount": 1, "shared_cradle": False,
                    "elevated_mounts": 1, "deck_mounts": 0, "depressed_mounts": 0})
        result, _reading, _batteries = evaluate_row(row)
        values = result["values"]
        expected = (2 * 0.75 + 1) / 3.0
        self.assertLess(relative(values["weight_adjustment"], expected), 1e-12)
        self.assertNotAlmostEqual(values["weight_adjustment"], 0.8)
        self.assertLess(relative(values["weight_adjustment"], 0.8333333333333334), 1e-12)
        self.assertEqual(values["mounts"], 3)
        # Group 1 carries two shared-cradle twin mounts (2 x 2 = 4 barrels) and
        # group 2 one single mount (1 x 1 = 1 barrel), so five guns are installed.
        self.assertEqual(values["installed_guns"], 5)
        calibre_in = row["calibre_mm"] / bl.MM_PER_INCH
        guns_lt = ce.gun_mass_long_tons(calibre_in, row["barrel_calibres"],
                                        ce.gun_date_factor(row["year"]), 5)
        # The shared-cradle factor is already inside the adjustment, so the mount
        # mass must not multiply 0.75 in a second time: shared_cradle stays False.
        expected_mounts = ce.mount_mass_long_tons(
            guns_lt, calibre_in, GUN_TYPES[row["gun_type_index"]],
            MOUNT_TYPES[row["mount_type_index"]],
            weight_adjustment=expected, shared_cradle=False)
        self.assertLess(relative(values["mounts_long_tons"], expected_mounts), 1e-12)
        doubled = ce.mount_mass_long_tons(
            guns_lt, calibre_in, GUN_TYPES[row["gun_type_index"]],
            MOUNT_TYPES[row["mount_type_index"]],
            weight_adjustment=expected, shared_cradle=True)
        self.assertNotAlmostEqual(values["mounts_long_tons"], doubled)
        # The second factor is exactly the recovered 0.75, applied once more.
        self.assertLess(relative(doubled, values["mounts_long_tons"] * 0.75), 1e-12)


class UnknownAndZeroTests(unittest.TestCase):
    """The distinction the contract draws between absent, unknown and zero."""

    def test_two_absent_groups_are_unavailable_rather_than_a_known_zero(self):
        row = synthetic_row()
        layout = layout_from_row(row, group1=_DELETE, group2=_DELETE)
        batteries = batteries_from_row(row)
        validated = bl.validate_layouts([layout], batteries)[0]
        reading = bl.evaluate(validated, batteries)
        result = bt.evaluate(layout, batteries, reading)
        self.assertEqual(result["status"], "unavailable")
        self.assertIsNone(result["values"]["guns_t"])
        self.assertIsNone(result["values"]["mounts_t"])
        self.assertIsNone(result["values"]["total_t"])
        self.assertTrue(any(d["code"] == "battery_totals.unconfigured"
                            for d in result["diagnostics"]), result["diagnostics"])

    def test_an_unknown_armour_blocks_only_the_total_and_keeps_guns_and_mounts(self):
        row = synthetic_row()
        # A missing face thickness leaves the complete layout armour unknown.
        result, _reading, _batteries = evaluate_row(
            row, armour={"face_mm": None})
        values = result["values"]
        self.assertEqual(result["status"], "partial")
        self.assertIsNotNone(values["guns_long_tons"])
        self.assertIsNotNone(values["mounts_long_tons"])
        self.assertIsNone(values["armour_long_tons"])
        self.assertIsNone(values["armour_t"])
        self.assertIsNone(values["total_long_tons"])
        self.assertIsNone(values["total_t"])
        self.assertTrue(any(d["code"] == "battery_totals.unknown" for d in result["diagnostics"]))

    def test_a_declared_zero_armour_is_a_real_zero_and_not_an_unknown(self):
        row = synthetic_row()
        result, _reading, _batteries = evaluate_row(
            row, armour={"face_mm": 0.0, "rear_roof_mm": 0.0, "barbette_mm": 0.0})
        values = result["values"]
        self.assertEqual(values["armour_long_tons"], 0.0)
        self.assertIsNotNone(values["total_long_tons"])
        self.assertEqual(values["total_long_tons"],
                         values["guns_long_tons"] + values["mounts_long_tons"])

    def test_two_absent_groups_leave_the_whole_battery_unknown_not_zero(self):
        row = synthetic_row()
        result, _reading, _batteries = evaluate_row(row)
        self.assertEqual(result["status"], "available")
        # Contrast with the unconfigured case above: an unknown mount count is
        # never read as a zero here.
        layout = layout_from_row(row, group1={"battery_id": None}, group2=_DELETE)
        batteries = batteries_from_row(row)
        validated = bl.validate_layouts([layout], batteries)[0]
        reading = bl.evaluate(validated, batteries)
        unknown = bt.evaluate(layout, batteries, reading)
        self.assertIsNone(unknown["values"]["guns_long_tons"])
        self.assertIsNone(unknown["values"]["weight_adjustment"])
        self.assertNotEqual(unknown["values"]["mounts"], 0)


class DifferingBarrelLengthTests(unittest.TestCase):
    """An older layout whose two rows disagree on barrel length stays usable."""

    def test_differing_barrel_calibres_make_the_whole_battery_total_unavailable(self):
        row = synthetic_row()
        batteries = batteries_from_row(row)
        # The two referenced rows declare different barrel lengths. The layout
        # kernel still reads them, because barrel length is not one of its shared
        # facts; this whole-battery kernel must refuse the gun and mount total.
        batteries[1] = dict(batteries[1], barrel_calibres=50)
        layout = layout_from_row(row)
        validated = bl.validate_layouts([layout], batteries)[0]
        reading = bl.evaluate(validated, batteries)
        self.assertIn(reading["status"], ("available", "partial"))
        result = bt.evaluate(layout, batteries, reading)
        self.assertIsNone(result["values"]["guns_long_tons"])
        self.assertIsNone(result["values"]["mounts_long_tons"])
        # The layout armour is still read and the project is not refused.
        self.assertIsNotNone(result["values"]["armour_long_tons"])
        self.assertEqual(result["status"], "partial")
        self.assertTrue(any(d["code"] == "battery_totals.contradiction"
                            for d in result["diagnostics"]), result["diagnostics"])

    def test_an_unknown_barrel_length_makes_the_whole_battery_total_unavailable(self):
        row = synthetic_row()
        batteries = batteries_from_row(row)
        batteries[1] = dict(batteries[1], barrel_calibres=None)
        layout = layout_from_row(row)
        validated = bl.validate_layouts([layout], batteries)[0]
        reading = bl.evaluate(validated, batteries)
        result = bt.evaluate(layout, batteries, reading)
        self.assertIsNone(result["values"]["guns_long_tons"])
        self.assertIsNotNone(result["values"]["armour_long_tons"])


class ProvenanceTests(unittest.TestCase):
    def test_provenance_records_the_inputs_groups_and_the_whole_battery_chain(self):
        row = synthetic_row()
        result, _reading, _batteries = evaluate_row(row)
        provenance = result["provenance"]
        self.assertEqual(provenance["method"], bt.METHOD_VERSION)
        self.assertEqual(provenance["source_sha256"], ce.SOURCE_SHA256)
        inputs = provenance["inputs"]
        self.assertEqual(inputs["installed_guns"], 5)
        self.assertEqual(inputs["mounts"], 3)
        self.assertFalse(inputs["shared_cradle"])
        self.assertEqual(inputs["group1"]["battery_id"], "main_g1")
        self.assertEqual(inputs["group2"]["mount_selector"], row["group2"]["selector"])
        self.assertEqual(inputs["layout_method_version"], bl.METHOD_VERSION)
        self.assertIn("weight_adjustment", inputs)

    def test_the_kernel_reads_a_supplied_layout_reading_without_recomputing_it(self):
        row = synthetic_row()
        layout = layout_from_row(row)
        batteries = batteries_from_row(row)
        validated = bl.validate_layouts([layout], batteries)[0]
        reading = bl.evaluate(validated, batteries)
        sentinel = dict(reading, armour={"values": {"total_long_tons": 12.5}})
        result = bt.evaluate(layout, batteries, sentinel)
        self.assertEqual(result["values"]["armour_long_tons"], 12.5)
        self.assertEqual(result["provenance"]["inputs"]["layout_method_version"],
                         bl.METHOD_VERSION)

    def test_every_declared_value_is_finite_json(self):
        for row in FIXTURE["rows"][:50] + FIXTURE["weight_adjustment_rows"][:20]:
            result, _reading, _batteries = evaluate_row(row)
            json.dumps(result, allow_nan=False)


