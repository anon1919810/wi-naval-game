"""Declared-versus-selected armour totals kernel.

Every expected number here is written out in the test, or is a plain sum of the
inputs the test itself supplies. Nothing is read from the project fixtures and
nothing is generated by the module under test: this kernel owns no recovered
expression, so its only honest oracle is the arithmetic in this file.
"""

