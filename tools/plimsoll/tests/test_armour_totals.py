import math
from pathlib import Path
import sys
import unittest

HERE = Path(__file__).resolve().parent
PKG = HERE.parent
if str(PKG) not in sys.path:
    sys.path.insert(0, str(PKG))

import armour_totals as at  # noqa: E402
import concept_estimates as ce  # noqa: E402

BELTS = ("belt_main", "belt_upper", "belt_ends")
NINE = ("belt_main", "belt_upper", "belt_ends", "bulkhead", "armour_bulge", "armour_deck",
        "conning", "rotating_armour", "gun_mount_armour")


def component(identity, kind, mass_t, target_id=None, method_version="sps-3b3-fixed-armour-v1"):
    return {"id": identity, "kind": kind, "target_id": target_id,
            "method_version": method_version, "mass_t": mass_t}


def declared_components():
    return [
        component("fixed:belt_main", "belt_main", 100.0, "weapons.belt_main"),
        component("fixed:belt_upper", "belt_upper", 40.0, "weapons.belt_upper"),
        component("fixed:belt_ends", "belt_ends", 25.0, "weapons.belt_ends"),
        component("fixed:bulkhead", "bulkhead", 12.0, "weapons.bulkhead"),
        component("fixed:armour_bulge", "armour_bulge", 8.0, None),
        component("fixed:armour_deck", "armour_deck", 30.0, "weapons.armour_deck"),
        component("fixed:conning", "conning", 5.0, "weapons.conning"),
        component("layout:weapons.main", "gun_mount_armour", 18.0, "weapons.main"),
    ]


def selected_roles(**overrides):
    roles = {role: 10.0 for role in NINE}
    roles["classification_complete"] = True
    roles.update(overrides)
    return roles


class ModuleIdentityTests(unittest.TestCase):
    def test_the_kernel_carries_its_own_method_version_and_role_tables(self):
        self.assertEqual(at.METHOD_VERSION, "sps-3b3-armour-totals-v1")
        self.assertNotEqual(at.METHOD_VERSION, ce.METHOD_VERSION)
        self.assertEqual(at.ID, "ship_armour")
        self.assertEqual(at.BELT_ROLES, BELTS)
        self.assertEqual(at.TOTAL_ROLES, NINE)
        self.assertEqual(at.VALUE_KEYS, ("estimated_belts_t", "estimated_total_t",
                                         "selected_belts_t", "selected_total_t",
                                         "known_estimate_subtotal_t"))

    def test_the_kernel_names_the_same_original_binary_without_inventing_one(self):
        self.assertEqual(at.kernels.SOURCE_ASSEMBLY, ce.SOURCE_ASSEMBLY)
        self.assertEqual(at.kernels.SOURCE_SHA256, ce.SOURCE_SHA256)


class DeclaredEstimateTests(unittest.TestCase):
    def test_a_confirmed_complete_declaration_sums_every_component_and_the_belts(self):
        result = at.evaluate(declared_components(), selected_roles(),
                             declared_complete=True, source="concept cruiser declaration")
        self.assertEqual(result["status"], "available")
        values = result["values"]
        self.assertAlmostEqual(values["estimated_total_t"], 100 + 40 + 25 + 12 + 8 + 30 + 5 + 18)
        self.assertAlmostEqual(values["estimated_belts_t"], 100 + 40 + 25)
        self.assertAlmostEqual(values["known_estimate_subtotal_t"], 100 + 40 + 25 + 12 + 8 + 30 + 5 + 18)
        self.assertEqual(result["coverage"]["declared_components"], 8)
        self.assertEqual(result["coverage"]["uncovered_component_ids"], [])
        self.assertEqual(result["source"], "concept cruiser declaration")

    def test_an_unconfirmed_declaration_leaves_the_complete_figures_unknown(self):
        for flag in (False, None):
            with self.subTest(declared_complete=flag):
                result = at.evaluate(declared_components(), selected_roles(),
                                     declared_complete=flag, source="s")
                values = result["values"]
                self.assertIsNone(values["estimated_total_t"])
                self.assertIsNone(values["estimated_belts_t"])
                self.assertAlmostEqual(values["known_estimate_subtotal_t"], 100 + 40 + 25 + 12 + 8 + 30 + 5 + 18)
                self.assertTrue(any(d["code"] == "armour_totals.incomplete_declaration"
                                    for d in result["diagnostics"]), result["diagnostics"])

    def test_one_unknown_component_makes_both_complete_figures_unknown_and_lists_it(self):
        components = declared_components()
        components[3] = component("fixed:bulkhead", "bulkhead", None, "weapons.bulkhead")
        result = at.evaluate(components, selected_roles(), declared_complete=True, source="s")
        values = result["values"]
        self.assertIsNone(values["estimated_total_t"])
        self.assertIsNone(values["estimated_belts_t"])
        self.assertAlmostEqual(values["known_estimate_subtotal_t"], 100 + 40 + 25 + 8 + 30 + 5 + 18)
        self.assertEqual(result["coverage"]["uncovered_component_ids"], ["fixed:bulkhead"])
        self.assertTrue(any(d["code"] == "armour_totals.unknown_component"
                            for d in result["diagnostics"]))
        # A partial sum never masquerades as the complete total: the subtotal
        # omits the unknown bulkhead and the complete figure stays unknown.
        self.assertAlmostEqual(values["known_estimate_subtotal_t"], 226.0)
        self.assertIsNone(values["estimated_total_t"])

    def test_a_declared_zero_component_is_a_real_zero_and_is_still_counted(self):
        components = declared_components()
        components[4] = component("fixed:armour_bulge", "armour_bulge", 0.0, None)
        result = at.evaluate(components, selected_roles(), declared_complete=True, source="s")
        values = result["values"]
        self.assertAlmostEqual(values["estimated_total_t"], 100 + 40 + 25 + 12 + 0 + 30 + 5 + 18)
        self.assertEqual(result["coverage"]["known_components"], 8)
        self.assertEqual(result["coverage"]["uncovered_component_ids"], [])

    def test_components_that_exist_but_are_all_unknown_have_no_known_subtotal(self):
        components = [component("fixed:belt_main", "belt_main", None, "weapons.belt_main")]
        result = at.evaluate(components, selected_roles(), declared_complete=True, source="s")
        self.assertIsNone(result["values"]["known_estimate_subtotal_t"])
        self.assertEqual(result["coverage"]["uncovered_component_ids"], ["fixed:belt_main"])

    def test_no_declared_components_is_a_declared_empty_scope_not_an_unknown(self):
        result = at.evaluate([], selected_roles(), declared_complete=True, source="s")
        values = result["values"]
        self.assertEqual(values["estimated_total_t"], 0.0)
        self.assertEqual(values["estimated_belts_t"], 0.0)
        self.assertEqual(values["known_estimate_subtotal_t"], 0.0)

    def test_belts_are_only_the_three_belt_roles(self):
        components = [
            component("fixed:belt_main", "belt_main", 1.0, "a"),
            component("fixed:belt_upper", "belt_upper", 2.0, "b"),
            component("fixed:belt_ends", "belt_ends", 4.0, "c"),
            component("fixed:bulkhead", "bulkhead", 100.0, "d"),
            component("fixed:conning", "conning", 1000.0, "e"),
        ]
        result = at.evaluate(components, selected_roles(), declared_complete=True, source="s")
        self.assertAlmostEqual(result["values"]["estimated_belts_t"], 7.0)
        self.assertAlmostEqual(result["values"]["estimated_total_t"], 1107.0)


class SelectedActualTests(unittest.TestCase):
    def test_a_fully_classified_ledger_yields_the_selected_belts_and_total(self):
        result = at.evaluate(declared_components(), selected_roles(),
                             declared_complete=True, source="s")
        values = result["values"]
        self.assertAlmostEqual(values["selected_belts_t"], 30.0)
        self.assertAlmostEqual(values["selected_total_t"], 90.0)

    def test_an_unclassified_ledger_leaves_the_selected_total_unknown_but_not_the_belts(self):
        result = at.evaluate(declared_components(),
                             selected_roles(classification_complete=False),
                             declared_complete=True, source="s")
        values = result["values"]
        self.assertAlmostEqual(values["selected_belts_t"], 30.0)
        self.assertIsNone(values["selected_total_t"])
        self.assertTrue(any(d["code"] == "armour_totals.selected_unknown"
                            for d in result["diagnostics"]))

    def test_a_missing_required_role_leaves_the_selected_figures_unknown_not_zero(self):
        for missing in BELTS:
            with self.subTest(missing=missing):
                roles = selected_roles()
                del roles[missing]
                result = at.evaluate(declared_components(), roles,
                                     declared_complete=True, source="s")
                self.assertIsNone(result["values"]["selected_belts_t"])
                self.assertIsNone(result["values"]["selected_total_t"])

    def test_missing_the_ledger_altogether_leaves_both_selected_figures_unknown(self):
        result = at.evaluate(declared_components(), None, declared_complete=True, source="s")
        self.assertIsNone(result["values"]["selected_belts_t"])
        self.assertIsNone(result["values"]["selected_total_t"])
        # The declared side is still fully known, so the reading is partial, not
        # unavailable: an unknown selected actual never erases a known estimate.
        self.assertEqual(result["status"], "partial")

    def test_a_selected_zero_role_is_a_real_zero_and_is_summed(self):
        result = at.evaluate(declared_components(),
                             selected_roles(belt_ends=0.0, conning=0.0),
                             declared_complete=True, source="s")
        values = result["values"]
        self.assertAlmostEqual(values["selected_belts_t"], 20.0)
        self.assertAlmostEqual(values["selected_total_t"], 70.0)

    def test_rotating_armour_appears_only_in_the_selected_actual(self):
        # No component kernel derives rotating_armour, so a declared estimate can
        # never contain it; the selected ledger still carries the nine-role sum.
        result = at.evaluate(declared_components(),
                             selected_roles(rotating_armour=77.0),
                             declared_complete=True, source="s")
        values = result["values"]
        self.assertAlmostEqual(values["selected_total_t"], 90.0 - 10.0 + 77.0)
        self.assertAlmostEqual(values["estimated_total_t"], 238.0)
        self.assertEqual(result["coverage"]["declared_components"], 8)


class StatusTests(unittest.TestCase):
    def test_status_is_available_only_when_both_the_declared_and_selected_totals_are_known(self):
        result = at.evaluate(declared_components(), selected_roles(),
                             declared_complete=True, source="s")
        self.assertEqual(result["status"], "available")

    def test_status_is_partial_when_one_side_is_unknown_but_the_other_is_known(self):
        result = at.evaluate(declared_components(),
                             selected_roles(classification_complete=None),
                             declared_complete=True, source="s")
        self.assertEqual(result["status"], "partial")

    def test_status_is_unavailable_when_no_figure_is_known(self):
        # A declared component with no mass, no confirmed complete declaration
        # and no ledger leaves every one of the five figures unknown.
        result = at.evaluate([component("fixed:x", "belt_main", None, "t")], None,
                             declared_complete=False, source="s")
        self.assertEqual(result["status"], "unavailable")
        for value in result["values"].values():
            self.assertIsNone(value)


class RefusalTests(unittest.TestCase):
    def refuse(self, *args, **kwargs):
        with self.assertRaises(at.ArmourTotalsError) as caught:
            at.evaluate(*args, **kwargs)
        return caught.exception

    def test_a_duplicated_component_id_is_refused(self):
        components = declared_components()
        components.append(component("fixed:belt_main", "belt_ends", 1.0, "other"))
        error = self.refuse(components, selected_roles(), declared_complete=True, source="s")
        self.assertTrue(any(d["code"] == "armour_totals.duplicate" for d in error.diagnostics))

    def test_a_duplicated_non_null_target_is_refused(self):
        components = declared_components()
        components.append(component("layout:weapons.secondary", "gun_mount_armour", 9.0,
                                    "weapons.main"))
        error = self.refuse(components, selected_roles(), declared_complete=True, source="s")
        self.assertTrue(any(d["code"] == "armour_totals.duplicate" for d in error.diagnostics))

    def test_null_targets_are_never_merged_into_one_another(self):
        components = [
            component("fixed:a", "belt_main", 1.0, None),
            component("fixed:b", "belt_upper", 2.0, None),
            component("fixed:c", "belt_ends", 3.0, None),
        ]
        result = at.evaluate(components, selected_roles(), declared_complete=True, source="s")
        self.assertAlmostEqual(result["values"]["estimated_total_t"], 6.0)
        self.assertEqual(result["coverage"]["declared_components"], 3)

    def test_an_unknown_kind_is_refused(self):
        error = self.refuse([component("fixed:x", "not_a_role", 1.0)],
                            selected_roles(), declared_complete=True, source="s")
        self.assertTrue(any(d["code"] == "armour_totals.enum" for d in error.diagnostics))

    def test_an_unsupported_component_field_is_refused(self):
        bad = component("fixed:x", "belt_main", 1.0, "t")
        bad["surprise"] = 5
        error = self.refuse([bad], selected_roles(), declared_complete=True, source="s")
        self.assertTrue(any(d["code"] == "armour_totals.unsupported_field"
                            for d in error.diagnostics))

    def test_a_non_finite_or_negative_mass_is_refused(self):
        for value in (float("nan"), float("inf"), float("-inf"), -1.0, "10", True):
            with self.subTest(mass_t=value):
                error = self.refuse([component("fixed:x", "belt_main", value, "t")],
                                    selected_roles(), declared_complete=True, source="s")
                self.assertTrue(any(d["code"] in ("armour_totals.invalid", "armour_totals.domain")
                                    for d in error.diagnostics))

    def test_a_non_boolean_completion_flag_is_refused(self):
        for kwargs in ({"declared_complete": "yes"},):
            with self.subTest(**kwargs):
                with self.assertRaises(at.ArmourTotalsError):
                    at.evaluate(declared_components(), selected_roles(), source="s", **kwargs)
        with self.assertRaises(at.ArmourTotalsError):
            at.evaluate(declared_components(),
                        dict(selected_roles(), classification_complete="maybe"),
                        declared_complete=True, source="s")


class RangeTests(unittest.TestCase):
    """A finite component or role can still sum past the finite range.

    Two finite component masses near the numeric limit overflow their sum, and so
    can two large selected roles. The pure interface must still return finite JSON:
    an overflowing aggregate is reported unknown with a structured range diagnostic
    rather than serialized as an infinity.
    """

    def test_an_overflowing_complete_estimate_is_unknown_and_still_finite_json(self):
        components = [component("fixed:a", "belt_main", 1e308, "a"),
                      component("fixed:b", "belt_upper", 1e308, "b")]
        result = at.evaluate(components, None, declared_complete=True, source="s")
        values = result["values"]
        self.assertIsNone(values["estimated_total_t"])
        self.assertIsNone(values["estimated_belts_t"])
        self.assertIsNone(values["known_estimate_subtotal_t"])
        self.assertTrue(any(d["code"] == "armour_totals.range" for d in result["diagnostics"]))
        json.dumps(result, allow_nan=False)

    def test_an_overflowing_partial_scope_subtotal_is_unknown_and_still_finite_json(self):
        components = [component("fixed:a", "belt_main", 1e308, "a"),
                      component("fixed:b", "belt_upper", 1e308, "b")]
        result = at.evaluate(components, None, declared_complete=False, source="s")
        self.assertIsNone(result["values"]["estimated_total_t"])
        self.assertIsNone(result["values"]["known_estimate_subtotal_t"])
        self.assertTrue(any(d["code"] == "armour_totals.range" for d in result["diagnostics"]))
        json.dumps(result, allow_nan=False)

    def test_an_overflowing_selected_sum_is_unknown_while_the_estimate_survives(self):
        huge = {role: 1e308 for role in NINE}
        huge["classification_complete"] = True
        result = at.evaluate(declared_components(), huge, declared_complete=True, source="s")
        values = result["values"]
        self.assertIsNone(values["selected_belts_t"])
        self.assertIsNone(values["selected_total_t"])
        # Each aggregate keeps its own fate: the declared estimate is untouched.
        self.assertAlmostEqual(values["estimated_total_t"], 238.0)
        self.assertTrue(any(d["code"] == "armour_totals.range" for d in result["diagnostics"]))
        json.dumps(result, allow_nan=False)

    def test_a_large_but_finite_sum_stays_a_finite_total(self):
        components = [component("fixed:a", "belt_main", 1e300, "a"),
                      component("fixed:b", "belt_upper", 1e300, "b")]
        result = at.evaluate(components, None, declared_complete=True, source="s")
        self.assertEqual(result["values"]["estimated_total_t"], 2e300)
        json.dumps(result, allow_nan=False)


class ProvenanceTests(unittest.TestCase):
    def test_provenance_records_the_declaration_and_the_component_identity(self):
        result = at.evaluate(declared_components(), selected_roles(),
                             declared_complete=True, source="concept cruiser declaration")
        provenance = result["provenance"]
        self.assertEqual(provenance["method"], at.METHOD_VERSION)
        self.assertEqual(provenance["source_sha256"], ce.SOURCE_SHA256)
        inputs = provenance["inputs"]
        self.assertEqual(inputs["declared_complete"], True)
        self.assertEqual(inputs["component_count"], 8)
        self.assertEqual(inputs["belt_component_ids"],
                         ["fixed:belt_main", "fixed:belt_upper", "fixed:belt_ends"])
        self.assertEqual(inputs["uncovered_component_ids"], [])
        self.assertEqual(inputs["selected_roles"]["belt_main"], 10.0)

    def test_every_reading_is_finite_json(self):
        for flag in (True, False, None):
            result = at.evaluate(declared_components(), selected_roles(),
                                 declared_complete=flag, source="s")
            json.dumps(result, allow_nan=False)

    def test_the_kernel_does_not_mutate_its_inputs(self):
        components = declared_components()
        roles = selected_roles()
        before_components = json.dumps(components, sort_keys=True)
        before_roles = json.dumps(roles, sort_keys=True)
        at.evaluate(components, roles, declared_complete=True, source="s")
        self.assertEqual(json.dumps(components, sort_keys=True), before_components)
        self.assertEqual(json.dumps(roles, sort_keys=True), before_roles)


