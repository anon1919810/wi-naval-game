FIXTURES = HERE / "fixtures/concept"
TOLERANCE = 1e-5


def load(name):
    return json.loads((FIXTURES / name).read_text(encoding="utf-8-sig"))


def relative(actual, expected):
    if expected == 0:
        return abs(actual)
    return abs(actual - expected) / abs(expected)


