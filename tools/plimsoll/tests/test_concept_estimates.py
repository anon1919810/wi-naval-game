class CanonicalConversionTests(unittest.TestCase):
    """The public canonical-unit wrappers, checked by hand."""

    def test_millimetres_to_inches_is_exactly_254_mm_per_inch(self):
        self.assertEqual(ce.millimetres_to_inches(25.4), 1.0)
        self.assertEqual(ce.millimetres_to_inches(254.0), 10.0)
        self.assertEqual(ce.millimetres_to_inches(1.0), 1.0 / 25.4)

    def test_metre_conversions(self):
        self.assertAlmostEqual(ce.metres_to_feet(0.3048), 1.0, places=12)
        self.assertAlmostEqual(ce.metres_to_inches(0.0254), 1.0, places=12)
        self.assertAlmostEqual(ce.metres_to_inches(1.0), 1.0 / 0.0254, places=9)

    def test_long_ton_and_kilogram_conversions(self):
        self.assertEqual(ce.LONG_TON_KG, 1016.0469088)
        self.assertEqual(ce.LB_PER_LONG_TON, 2240.0)
        self.assertEqual(ce.KW_PER_HP, 0.746)
        self.assertAlmostEqual(ce.long_tons_to_tonnes(1.0), 1.0160469088, places=12)
        self.assertAlmostEqual(ce.kg_to_long_tons(1016.0469088), 1.0, places=12)
        self.assertAlmostEqual(ce.pounds_to_kilograms(1.0), 0.45359237, places=12)
        self.assertAlmostEqual(ce.kilograms_to_pounds(0.45359237), 1.0, places=9)
        self.assertAlmostEqual(ce.hp_to_kw(100.0), 74.6, places=12)

    def test_seawater_constant_is_cubic_feet_per_long_ton(self):
        # 2240 lb at 64 lb/ft^3 is 35 ft^3 per long ton. It is a specific
        # volume, not a density, and must never be used as lb/ft^3.
        self.assertEqual(ce.SEAWATER_CUBIC_FT_PER_LONG_TON, 35.0)
        self.assertEqual(ce.SEAWATER_CUBIC_FT_PER_LONG_TON, ce.LB_PER_LONG_TON / 64.0)
        self.assertFalse(hasattr(ce, "SALT_WATER_LB_PER_FT3"))

    def test_conversions_reject_nonfinite_and_nonpositive(self):
        for bad in (float("nan"), float("inf"), 0.0, -1.0, True, "10", None):
            with self.subTest(value=bad), self.assertRaises(ValueError):
                ce.millimetres_to_inches(bad)


class OriginalGunVectorTests(unittest.TestCase):
    """All 67 original-assembly gun vectors."""

    @classmethod
    def setUpClass(cls):
        cls.rows = load("original-gun-vectors.json")["rows"]

    def test_vector_count(self):
        self.assertEqual(len(self.rows), 67)

    def test_every_original_vector_is_reproduced(self):
        worst = 0.0
        for row in self.rows:
            factor = ce.gun_date_factor(row["year"])
            shell = ce.estimated_shell_lb(row["calibre_in"], row["barrel_calibres"], factor)
            guns = ce.gun_mass_long_tons(row["calibre_in"], row["barrel_calibres"], factor,
                                         row["installed_guns"])
            mounts = ce.mount_mass_long_tons(
                guns, row["calibre_in"], ce.GUN_TYPES[row["gun_type_index"]],
                ce.MOUNT_TYPES[row["mount_type_index"]], row["mount_adjustment"],
                row["weight_adjustment"])
            ammo = ce.ammunition_long_tons(row["installed_guns"], row["rounds_per_gun"], shell)
            for key, actual in (("date_factor", factor), ("shell_lb", shell),
                                ("guns_long_tons", guns), ("mounts_long_tons", mounts),
                                ("ammunition_long_tons", ammo)):
                error = relative(actual, row[key])
                worst = max(worst, error)
                self.assertLessEqual(error, TOLERANCE, "%s %r" % (key, row))
        self.assertLess(worst, 1e-5)


class OriginalPowerVectorTests(unittest.TestCase):
    """All 30 original-assembly speedHpCalc vectors."""

    @classmethod
    def setUpClass(cls):
        payload = load("original-power-vectors.json")
        cls.inputs = payload["inputs"]
        cls.rows = payload["rows"]

    def test_vector_count(self):
        self.assertEqual(len(self.rows), 30)

    def test_every_original_vector_is_reproduced(self):
        inputs = self.inputs
        for row in self.rows:
            effect = ce.effective_length_ft(inputs["length_ft"], inputs["beam_bulges_ft"],
                                            inputs["coSharp"], ce.STERN_TYPES[row["stern_index"]])
            hp, length_hp = ce.speed_hp(row["speed_kn"], inputs["length_ft"], effect,
                                        inputs["coSharp"], inputs["displacement_long_tons"],
                                        inputs["wetted_surface_sqft"], row["engine_year"])
            for key, actual in (("length_effect_ft", effect), ("length_hp_ft", length_hp),
                                ("power_hp", hp)):
                self.assertLessEqual(relative(actual, row[key]), TOLERANCE, "%s %r" % (key, row))

    def test_stern_conditioning_is_exact(self):
        inputs = self.inputs
        lengths = {}
        for index, name in enumerate(ce.STERN_TYPES):
            lengths[name] = ce.effective_length_ft(inputs["length_ft"], inputs["beam_bulges_ft"],
                                                   inputs["coSharp"], name)
        length = inputs["length_ft"]
        self.assertEqual(lengths["cruiser"], length)
        self.assertEqual(lengths["round"], length)
        self.assertLessEqual(relative(
            lengths["small_transom"], length + 0.5 * inputs["beam_bulges_ft"] / inputs["coSharp"]),
            1e-12)
        self.assertLessEqual(relative(
            lengths["large_transom"], length + inputs["beam_bulges_ft"] / inputs["coSharp"]),
            1e-12)

    def test_power_length_branches_follow_the_speed(self):
        # The recovered low-speed branch is length - (lengthEffect - length), so the
        # power length shortens as the effective length grows.
        length, effect = 600.0, 700.0
        self.assertEqual(ce.power_length_ft(10.0, length, effect), 500.0)
        self.assertEqual(ce.power_length_ft(15.0, length, effect), 500.0)
        self.assertEqual(ce.power_length_ft(25.0, length, effect), effect)
        self.assertEqual(ce.power_length_ft(30.0, length, effect), effect)
        self.assertAlmostEqual(ce.power_length_ft(20.0, length, effect), length, places=12)
        self.assertAlmostEqual(ce.power_length_ft(22.5, length, effect), length + 0.5 * 100,
                               places=12)
        # A cruiser stern has lengthEffect == length, so every speed uses the length.
        self.assertEqual(ce.power_length_ft(10.0, length, length), length)

    def test_nonpositive_effective_power_length_is_rejected(self):
        # A lengthEffect beyond twice the length drives the low-speed branch negative.
        with self.assertRaises(ValueError) as caught:
            ce.speed_hp(10.0, 600.0, 2000.0, 0.38, 5000.0, 1000.0, 1900)
        self.assertIn("power length", str(caught.exception))


