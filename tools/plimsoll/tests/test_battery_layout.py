M_PER_FT = ce.M_PER_FT
MM_PER_INCH = ce.M_PER_INCH * 1000.0
INCH_MM = 25.4


def inches_to_mm(value):
    """The nominal decimal conversion, so twelve inches is exactly 304.8 mm.

    ``float(12 * 25.4)`` is 304.79999999999995 in binary64 and reads back as
    11.999999999999998 inches, which would wrongly cross the recovered
    ``calibre < 12`` branch. The original assembly's inches are a nominal decimal
    value, so the conversion goes through Decimal and never clamps the product.
    """
    return float(Decimal(str(value)) * Decimal("25.4"))


def feet_to_m(value):
    return round(value * M_PER_FT, 9)


def close(actual, expected, tolerance=1e-9):
    """A relative comparison; nothing here clamps or rewrites either side."""
    if expected == 0:
        return abs(actual) <= tolerance
    return abs(actual - expected) <= tolerance * abs(expected)
# The recovered empirical mass constant (MainForm.cs:22) and the recovered
# fifteen-entry gunsInMount table (GunControl.cs:636 perMountCalc).
INCH_CONSTANT = 0.0185
PER_MOUNT = (1, 2, 4, 2, 2, 4, 3, 3, 6, 4, 4, 8, 5, 5, 10)
DIAMETER_CLASS = {}
for _index in range(15):
    if _index <= 2:
        DIAMETER_CLASS[_index] = (1.44, 0.609725)
    elif _index <= 5:
        DIAMETER_CLASS[_index] = (1.52, 0.4205)
    elif _index <= 8:
        DIAMETER_CLASS[_index] = (1.64, 0.29)
    elif _index <= 11:
        DIAMETER_CLASS[_index] = (1.8, 0.2)
    else:
        DIAMETER_CLASS[_index] = (2.0, 0.14)
SHARED_SELECTORS = (3, 6, 9, 12)
BARBETTE_COEFFICIENT = {2: 0.6416, 3: 0.5, 4: 0.1, 6: 0.1}


def date_fourth_root(year):
    """GunControl.cs:429 then :1222: the barbette year factor is a fourth root."""
    return math.sqrt(ce.gun_date_factor(year))


def reference_group_freeboard(layout_index, mounts, profile, reaches_half):
    """A longhand transcription of GunControl.cs:678-757 for one group."""
    forward = profile["forward_fore_m"] + (profile["forward_aft_m"]
                                           - profile["forward_fore_m"]) * 0.5
    aft = profile["aft_fore_m"] + (profile["aft_aft_m"] - profile["aft_fore_m"]) * 0.5
    fore, fore_aft = profile["forward_fore_m"], profile["forward_aft_m"]
    aft_fore, aft_aft = profile["aft_fore_m"], profile["aft_aft_m"]
    banked = layout_index in (0, 9)
    if ((banked and reaches_half and mounts == 1)
            or (layout_index in (1, 10) and mounts == 1)
            or 2 < layout_index < 6 or 11 < layout_index < 15):
        placed = float(mounts)
    elif (banked and reaches_half) or layout_index in (1, 10):
        placed = float(round(mounts * 0.5))
    elif ((banked and not reaches_half and mounts == 1)
          or (layout_index in (2, 11) and mounts == 1)
          or 5 < layout_index < 9 or layout_index > 14):
        placed = 0.0
    else:
        placed = float(mounts) - float(round(mounts * 0.5))
    rest = float(mounts) - placed
    if mounts <= 0:
        return 0.0, placed
    if layout_index in (0, 9):
        return (placed * forward + rest * aft) / float(mounts), placed
    result = 0.0
    if layout_index in (1, 2, 10, 11):
        if placed > 0:
            result = placed * ((fore - forward) / placed * 0.5 + (fore + forward) * 0.5)
        if rest > 0:
            result += rest * ((aft_aft - aft) / rest * 0.5 + (aft_aft + aft) * 0.5)
        return result / float(mounts), placed
    if layout_index in (3, 12):
        if placed > 0:
            return (fore - forward) / placed * 0.5 + (fore + forward) * 0.5, placed
        return 0.0, placed
    if layout_index in (4, 13):
        return forward, placed
    if layout_index in (5, 14):
        if placed > 0:
            return (fore_aft - forward) / placed * 0.5 + (fore_aft + forward) * 0.5, placed
        return 0.0, placed
    if layout_index in (6, 15):
        if rest > 0:
            return (aft_fore - aft) / rest * 0.5 + (aft_fore + aft) * 0.5, placed
        return 0.0, placed
    if layout_index in (7, 16):
        return aft, placed
    if layout_index in (8, 17):
        if rest > 0:
            return (aft_aft - aft) / rest * 0.5 + (aft_aft + aft) * 0.5, placed
        return 0.0, placed
    return None, placed


def reference_layout_chain(row):
    """A longhand transcription of the recovered mountsCalc chain for one row.

    Given one original ``mountsCalc`` case it recomputes the position-weighted
    freeboard, the height factor and the complete two-group armour from the
    declared inputs only. Written independently of the module under test so a
    shared structural mistake cannot hide.
    """
    profile = {"forecastle_fraction": row["deck_profile"]["forecastle_fraction"],
               "forward_deck_fraction": row["deck_profile"]["forward_deck_fraction"],
               "forward_fore_m": row["deck_profile"]["forward_fore_ft"] * M_PER_FT,
               "forward_aft_m": row["deck_profile"]["forward_aft_ft"] * M_PER_FT,
               "aft_fore_m": row["deck_profile"]["aft_fore_ft"] * M_PER_FT,
               "aft_aft_m": row["deck_profile"]["aft_aft_ft"] * M_PER_FT}
    reaches_half = (profile["forecastle_fraction"] + profile["forward_deck_fraction"]) >= 0.5
    calibre_in = row["calibre_in"]
    readings = []
    for name in ("group1", "group2"):
        group = row[name]
        selector = group["selector"]
        per_mount = PER_MOUNT[selector]
        mounts = (group["elevated_mounts"] + group["deck_mounts"] + group["depressed_mounts"])
        weight_adj = 0.75 if selector in SHARED_SELECTORS else 1.0
        freeboard, _placed = reference_group_freeboard(group["layout_index"], mounts, profile,
                                                      reaches_half)
        diameter = DIAMETER_CLASS[selector][0] * calibre_in * (
            1 + (1 / calibre_in) ** DIAMETER_CLASS[selector][1])
        if calibre_in < 12:
            diameter += 12 / calibre_in
        if calibre_in > 1 and weight_adj < 1:
            diameter *= 0.9
        readings.append({"selector": selector, "per_mount": per_mount, "mounts": mounts,
                         "weight_adj": weight_adj, "diameter": diameter,
                         "elevated": group["elevated_mounts"],
                         "depressed": group["depressed_mounts"],
                         "freeboard_m": freeboard})
    total_mounts = sum(reading["mounts"] for reading in readings)
    barrels = sum(reading["mounts"] * PER_MOUNT[reading["selector"]] for reading in readings)
    freeboard_m = None
    if total_mounts:
        freeboard_m = sum(reading["freeboard_m"] * reading["mounts"]
                          for reading in readings) / float(total_mounts)
    doubled_elevated = 2 if row["group2_double_elevation"] else 1
    doubled_depressed = 2 if row["group2_double_depression"] else 1
    first, second = readings
    ratio = ((first["elevated"] * first["per_mount"]
              + second["elevated"] * second["per_mount"] * doubled_elevated)
             - (first["depressed"] * first["per_mount"]
                + second["depressed"] * second["per_mount"] * doubled_depressed)) / barrels
    super_factor = None
    if barrels == 0:
        super_factor = 1.0
    elif freeboard_m:
        freeboard_ft = freeboard_m / M_PER_FT
        super_factor = (ratio * max(7.5, calibre_in * 0.6) + freeboard_ft) / freeboard_ft

    mount_index = ce.MOUNT_TYPES.index(FIXTURE["vocabulary"]["mount_types"][row["mount_type_index"]])
    gun_index = ce.GUN_TYPES.index(FIXTURE["vocabulary"]["gun_types"][row["gun_type_index"]])
    height = max(7.5, 0.625 * calibre_in * (2.0 if mount_index == 1 else 1.0))
    summed = sum(reading["diameter"] * reading["mounts"] for reading in readings)
    disc = sum(math.pi * (reading["diameter"] / 2.0) ** 2 * reading["mounts"]
               for reading in readings)
    face_in = row["arm_in"]["face"]
    rear_in = row["arm_in"]["rear_roof"]
    barbette_in = row["arm_in"]["barbette"]
    if mount_index in (0, 6):
        face_coefficient = 1.0
    elif mount_index == 1:
        face_coefficient = math.pi / 2
    elif mount_index == 2:
        face_coefficient = 0.0
    elif rear_in == 0:
        face_coefficient = 1.5
    else:
        face_coefficient = 0.5
    face = face_coefficient * summed * height * face_in * INCH_CONSTANT
    if gun_index == 3 or (gun_index == 6 and rear_in == 0):
        face *= 0.333
    if mount_index == 1:
        back = disc
    else:
        back = (2.5 if 2 < mount_index < 6 else 0.0) * summed * height + disc * 0.75
    back *= rear_in * INCH_CONSTANT
    per_mounts = 0
    weighted = 0
    counted = 0
    for reading in readings:
        if reading["mounts"] == 0:
            continue
        weighted += reading["per_mount"] * reading["mounts"]
        counted += reading["mounts"]
    per_mounts = weighted // counted if counted else 0
    if ce.MOUNT_ADJUSTMENT[mount_index] > 0.5:
        barbette_per_mounts = min(4, per_mounts)
    else:
        barbette_per_mounts = per_mounts
    coefficient = BARBETTE_COEFFICIENT.get(mount_index, 0.0)
    if freeboard_m and freeboard_m > 0 and coefficient and super_factor is not None:
        barbette = (1 - (barbette_per_mounts - 2) / 6) * (barbette_in * barrels
                                                         * calibre_in ** 1.2 * coefficient
                                                         * (freeboard_m / M_PER_FT) / 16
                                                         * super_factor * coefficient * 2
                                                         * date_fourth_root(row["year"]))
    else:
        barbette = 0.0
    return {"freeboard_m": freeboard_m, "super_factor": super_factor,
            "mounts": total_mounts, "barrels": barrels, "per_mounts": per_mounts,
            "barbette_per_mounts": barbette_per_mounts,
            "face_long_tons": face, "rear_roof_long_tons": back,
            "barbette_long_tons": barbette,
            "total_long_tons": face + back + barbette,
            "groups": {name: {"freeboard_m": reading["freeboard_m"],
                              "diameter_ft": reading["diameter"],
                              "mounts": reading["mounts"], "per_mount": reading["per_mount"]}
                       for name, reading in zip(("group1", "group2"), readings)}}


def batteries_from_row(row):
    """Two normalized battery rows that a fixture row can reference."""
    rows = []
    for name in ("group1", "group2"):
        group = row[name]
        rows.append({"id": "main_g%s" % (name[-1],), "calibre_mm": row["calibre_mm"],
                     "year": row["year"],
                     "gun_type": FIXTURE["vocabulary"]["gun_types"][row["gun_type_index"]],
                     "mount_type": FIXTURE["vocabulary"]["mount_types"][row["mount_type_index"]],
                     "mount_count": (group["elevated_mounts"] + group["deck_mounts"]
                                     + group["depressed_mounts"]),
                     "barrels_per_mount": group["per_mount"],
                     "shared_cradle": group["shared_cradle"]})
    return rows


def layout_from_row(row, **overrides):
    """One layout declaration that reproduces an original ``mountsCalc`` case."""
    profile = {"forecastle_fraction": row["deck_profile"]["forecastle_fraction"],
               "forward_deck_fraction": row["deck_profile"]["forward_deck_fraction"],
               "forward_fore_m": feet_to_m(row["deck_profile"]["forward_fore_ft"]),
               "forward_aft_m": feet_to_m(row["deck_profile"]["forward_aft_ft"]),
               "aft_fore_m": feet_to_m(row["deck_profile"]["aft_fore_ft"]),
               "aft_aft_m": feet_to_m(row["deck_profile"]["aft_aft_ft"])}
    layout = {
        "id": "case-%s" % (row["case_id"].lower(),),
        "source": "original assembly reading %s" % row["case_id"],
        "group1": {"battery_id": "main_g1", "mount_selector": row["group1"]["selector"],
                   "layout_index": row["group1"]["layout_index"],
                   "elevated_mounts": row["group1"]["elevated_mounts"],
                   "deck_mounts": row["group1"]["deck_mounts"],
                   "depressed_mounts": row["group1"]["depressed_mounts"]},
        "group2": {"battery_id": "main_g2", "mount_selector": row["group2"]["selector"],
                   "layout_index": row["group2"]["layout_index"],
                   "elevated_mounts": row["group2"]["elevated_mounts"],
                   "deck_mounts": row["group2"]["deck_mounts"],
                   "depressed_mounts": row["group2"]["depressed_mounts"]},
        "group2_double_elevation": row["group2_double_elevation"],
        "group2_double_depression": row["group2_double_depression"],
        "deck_profile": profile,
        "armour": {"system_id": "weapons.main", "item_id": "weapons.main_layout_armour",
                   "face_mm": row["arm_mm"]["face"],
                   "rear_roof_mm": row["arm_mm"]["rear_roof"],
                   "barbette_mm": row["arm_mm"]["barbette"]},
    }
    for key, value in overrides.items():
        if value is _DELETE:
            layout.pop(key, None)
        elif isinstance(value, dict) and isinstance(layout.get(key), dict):
            layout[key] = dict(layout[key], **value)
        else:
            layout[key] = value
    return layout


class _Delete:
    """Sentinel for a key an override must remove."""

    def __repr__(self):                                 # pragma: no cover - debugging aid
        return "<delete>"


_DELETE = _Delete()


def evaluate_row(row, **overrides):
    layout = layout_from_row(row, **overrides)
    batteries = batteries_from_row(row)
    validated = bl.validate_layouts([layout], batteries)
    return bl.evaluate(validated[0], batteries), validated[0], batteries


def relative(actual, expected):
    if expected == 0:
        return abs(actual)
    return abs(actual - expected) / abs(expected)


class ModuleIdentityTests(unittest.TestCase):
    def test_the_kernel_and_its_armour_carry_their_own_method_versions(self):
        self.assertEqual(bl.METHOD_VERSION, "sps-3b3-battery-layout-v1")
        self.assertEqual(bl.ARMOUR_METHOD_VERSION, "sps-3b3-battery-armour-v2")
        self.assertNotEqual(bl.METHOD_VERSION, ce.METHOD_VERSION)

    def test_the_kernel_names_the_same_original_binary_without_inventing_one(self):
        self.assertEqual(bl.SOURCE_ASSEMBLY, ce.SOURCE_ASSEMBLY)
        self.assertEqual(bl.SOURCE_SHA256, ce.SOURCE_SHA256)
        # The fixture records the original binary's own hash, and separately the
        # hash of the evidence file the readings were extracted from.
        self.assertEqual(FIXTURE["source_sha256"], ce.SOURCE_SHA256)
        self.assertEqual(FIXTURE["source_binary_sha256"], ce.SOURCE_SHA256)
        for name, digest in FIXTURE["evidence_file_sha256"].items():
            self.assertRegex(digest, r"\A[0-9a-f]{64}\Z", name)

    def test_the_kernel_never_becomes_the_configuration_method(self):
        self.assertEqual(ce.METHOD_VERSION, "sps-3b3-adapted-v1")

    def test_the_recovered_selector_table_matches_the_original_assembly(self):
        self.assertEqual(list(bl.PER_MOUNT_BY_SELECTOR), list(PER_MOUNT))
        table = FIXTURE["selector_table"]
        for index in range(15):
            self.assertEqual(table["per_mount"][str(index)], bl.PER_MOUNT_BY_SELECTOR[index])
            weight = table["weight_adjustment"][str(index)]
            self.assertEqual(weight, bl.WEIGHT_ADJUSTMENT_BY_SELECTOR[index])
        for index in range(15, 19):
            # The original's table stops at fifteen selectors and returns zero.
            self.assertEqual(table["per_mount"][str(index)], 0)


class FreeboardTests(unittest.TestCase):
    """Every layout, mount count, deck shape and rounding case the original ran."""

    def test_every_original_freeboard_reading_is_reproduced(self):
        worst = 0.0
        checked = 0
        for row in FIXTURE["freeboard_rows"]:
            profile = {"forecastle_fraction": None, "forward_deck_fraction": None,
                       "forward_fore_m": feet_to_m(row["deck_profile"]["forward_fore_ft"]),
                       "forward_aft_m": feet_to_m(row["deck_profile"]["forward_aft_ft"]),
                       "aft_fore_m": feet_to_m(row["deck_profile"]["aft_fore_ft"]),
                       "aft_aft_m": feet_to_m(row["deck_profile"]["aft_aft_ft"])}
            reads_fractions = row["layout_index"] in (0, 9)
            if row["deck_profile"]["fore_length_sum"] is None:
                # The rounding family declares no fractions. Layouts 0 and 9 are
                # the only ones that read them, so only the rest is comparable.
                if reads_fractions:
                    continue
                for fraction in (0.375, 0.625):
                    value = bl.free_gun_m(row["layout_index"], row["mounts"],
                                          dict(profile, forecastle_fraction=fraction,
                                               forward_deck_fraction=0.0))
                    self.assertTrue(close(value / M_PER_FT,
                                          row["original"]["freeboard_ft"], 1e-6),
                                    row["case_id"])
                    checked += 1
                continue
            profile["forecastle_fraction"] = row["deck_profile"]["fore_length_sum"]
            profile["forward_deck_fraction"] = 0.0
            value = bl.free_gun_m(row["layout_index"], row["mounts"], profile)
            self.assertIsNotNone(value, row["case_id"])
            # The original stored its own readings in single precision, so the
            # comparison carries that rounding and no tolerance is invented per
            # case beyond it.
            error = relative(value / M_PER_FT, row["original"]["freeboard_ft"])
            worst = max(worst, error)
            checked += 1
        self.assertGreater(checked, 300)
        self.assertLess(worst, 1e-6)

    def test_the_midpoint_rounding_is_ties_to_even(self):
        profile = {"forecastle_fraction": 0.375, "forward_deck_fraction": 0.0,
                   "forward_fore_m": 2.4, "forward_aft_m": 2.4,
                   "aft_fore_m": 2.4, "aft_aft_m": 2.4}
        # Layout 1 splits an even-and-up group with Math.Round(mounts * 0.5, 0),
        # whose midpoint rule is ties to even: three mounts place two forward,
        # five mounts place two forward and three aft.
        placed = {mounts: bl.mounts_for(1, mounts, True) for mounts in range(0, 10)}
        self.assertEqual(placed, {0: 0.0, 1: 1.0, 2: 1.0, 3: 2.0, 4: 2.0, 5: 2.0,
                                 6: 3.0, 7: 4.0, 8: 4.0, 9: 4.0})
        # A floor would place three for five mounts and a ceiling four; the
        # recovered rule places two.
        self.assertEqual(bl.mounts_for(1, 5, True), 2.0)
        self.assertEqual(bl.mounts_for(3, 5, True), 5.0)
        for mounts in range(1, 10):
            self.assertTrue(close(bl.free_gun_m(1, mounts, profile), 2.4, 1e-9), mounts)
        self.assertEqual(bl.free_gun_m(1, 0, profile), 0.0)

    def test_a_flush_deck_moves_a_single_centrally_mounted_gun_aft(self):
        profile = {"forward_fore_m": 2.6, "forward_aft_m": 2.2, "aft_fore_m": 2.0,
                   "aft_aft_m": 1.6}
        flush = dict(profile, forecastle_fraction=0.2, forward_deck_fraction=0.2)
        raised = dict(profile, forecastle_fraction=0.3, forward_deck_fraction=0.3)
        self.assertTrue(close(bl.free_gun_m(0, 1, flush), 1.8, 1e-9))
        self.assertTrue(close(bl.free_gun_m(0, 1, raised), 2.4, 1e-9))
        self.assertTrue(close(bl.free_gun_m(9, 1, flush), 1.8, 1e-9))
        self.assertTrue(close(bl.free_gun_m(9, 1, raised), 2.4, 1e-9))

    def test_an_unknown_deck_profile_is_not_a_flat_deck(self):
        # Layouts 0 and 9 read the two length fractions, so an unknown fraction
        # leaves their freeboard unknown. Every other recovered layout never reads
        # them, so an unknown fraction is irrelevant there and must not block it.
        profile = {"forecastle_fraction": None, "forward_deck_fraction": None,
                   "forward_fore_m": 2.6, "forward_aft_m": 2.2, "aft_fore_m": 2.0,
                   "aft_aft_m": 1.6}
        for layout_index in (0, 9):
            for mounts in (1, 3):
                self.assertIsNone(bl.free_gun_m(layout_index, mounts, profile),
                                  (layout_index, mounts))
        self.assertTrue(close(bl.free_gun_m(7, 3, profile), 1.8, 1e-9))
        self.assertTrue(close(bl.free_gun_m(4, 3, profile), 2.4, 1e-9))
        # A missing height is unknown only for the layouts that read it: the
        # aft-deck layouts never read the forward deck heights.
        for layout_index in (0, 1, 2, 3, 4, 5, 9, 10, 11, 12, 13, 14):
            incomplete = dict(profile, forward_fore_m=None)
            self.assertIsNone(bl.free_gun_m(layout_index, 3, incomplete), layout_index)
        for layout_index in (6, 7, 8, 15, 16, 17):
            incomplete = dict(profile, aft_fore_m=None)
            self.assertIsNone(bl.free_gun_m(layout_index, 3, incomplete), layout_index)

    def test_a_zero_mount_group_reads_a_determined_zero(self):
        profile = {"forecastle_fraction": 0.3, "forward_deck_fraction": 0.3,
                   "forward_fore_m": 2.6, "forward_aft_m": 2.2, "aft_fore_m": 2.0,
                   "aft_aft_m": 1.6}
        self.assertEqual(bl.free_gun_m(4, 0, profile), 0.0)


class HandComputedTests(unittest.TestCase):
    """The spec's own analytic sample, worked out here rather than imported."""

    def test_the_spec_sample_reproduces_its_hand_computed_readings(self):
        row = {"case_id": "spec", "calibre_mm": inches_to_mm(12), "calibre_in": 12.0,
               "year": 1910, "gun_type_index": 1, "mount_type_index": 3,
               "deck_profile": {"forecastle_fraction": 0.2, "forward_deck_fraction": 0.3,
                               "forward_fore_ft": 7 / M_PER_FT, "forward_aft_ft": 5 / M_PER_FT,
                               "aft_fore_ft": 5 / M_PER_FT, "aft_aft_ft": 4 / M_PER_FT},
               "group1": {"selector": 4, "layout_index": 1, "per_mount": 2,
                          "shared_cradle": False, "elevated_mounts": 1, "deck_mounts": 1,
                          "depressed_mounts": 0},
               "group2": {"selector": 7, "layout_index": 7, "per_mount": 3,
                          "shared_cradle": False, "elevated_mounts": 0, "deck_mounts": 1,
                          "depressed_mounts": 0},
               "group2_double_elevation": False, "group2_double_depression": False,
               "arm_mm": {"face": inches_to_mm(10), "rear_roof": inches_to_mm(5),
                          "barbette": inches_to_mm(6)},
               "arm_in": {"face": 10, "rear_roof": 5, "barbette": 6}}
        result, _layout, _batteries = evaluate_row(row)
        self.assertEqual(result["status"], "available")
        self.assertTrue(close(result["freeboard_m"], 15.5 / 3.0, 1e-12))
        self.assertTrue(close(result["super_factor"],
                              1.0 + ((2 / 7.0) * 7.5 * M_PER_FT) / (15.5 / 3.0), 1e-12))
