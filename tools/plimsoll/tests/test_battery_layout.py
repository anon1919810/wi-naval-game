"""Two-group battery layout, freeboard, height factor and mixed armour kernel.

Every expected number in this file comes from one of three independent places:

* ``reference_layout_chain`` below, a longhand transcription of the recovered
  ``GunControl.cs`` expressions written without the module under test;
* ``fixtures/concept/original-layout-vectors.json``, a curated, separately
  provenanced extraction of the original assembly's own readings (see its
  ``scope``/``source_sha256``/``units`` fields);
* arithmetic written out in the test itself, such as the spec's hand sample.

Nothing here is generated by the module under test, and nothing here claims to
be a whole-program parity statement: the per-group gun, mount and ammunition
estimates remain ``sps-3b3-adapted-v1`` per battery row.
"""

