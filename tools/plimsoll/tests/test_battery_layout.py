    def _layout(self, **overrides):
        layout = {"id": "main-layout", "source": "declared synthetic layout",
                  "group1": {"battery_id": "main", "mount_selector": 4, "layout_index": 1,
                             "elevated_mounts": 1, "deck_mounts": 1, "depressed_mounts": 0},
                  "group2": {"battery_id": "second", "mount_selector": 7, "layout_index": 7,
                             "elevated_mounts": 0, "deck_mounts": 1, "depressed_mounts": 0},
                  "group2_double_elevation": False, "group2_double_depression": False,
                  "deck_profile": {"forecastle_fraction": 0.2, "forward_deck_fraction": 0.3,
                                   "forward_fore_m": 2.2, "forward_aft_m": 1.6,
                                   "aft_fore_m": 1.6, "aft_aft_m": 1.2},
                  "armour": None}
        for key, value in overrides.items():
            if value is _DELETE:
                layout.pop(key, None)
            elif isinstance(value, dict) and isinstance(layout.get(key), dict):
                layout[key] = dict(layout[key], **value)
            else:
                layout[key] = value
        return layout

    def _refuse(self, layout, batteries=None, code=None):
        with self.assertRaises(bl.LayoutValidationError) as raised:
            bl.validate_layouts([layout], batteries if batteries is not None
                                else self.BATTERIES)
        codes = {d["code"] for d in raised.exception.diagnostics}
        self.assertTrue(codes, raised.exception.diagnostics)
        if code is not None:
            self.assertIn(code, codes)
        return raised.exception.diagnostics

    def test_a_valid_declaration_normalizes_to_the_declared_keys(self):
        validated = bl.validate_layouts([self._layout()], self.BATTERIES)
        self.assertEqual(len(validated), 1)
        layout = validated[0]
        self.assertEqual(set(layout), set(bl.LAYOUT_FIELDS))
        self.assertEqual(set(layout["group1"]), set(bl.GROUP_FIELDS))
        self.assertEqual(set(layout["deck_profile"]), set(bl.DECK_PROFILE_FIELDS))
        self.assertEqual(layout["group1"]["mount_selector"], 4)
        self.assertEqual(layout["deck_profile"]["forward_fore_m"], 2.2)

