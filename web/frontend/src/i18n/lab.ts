/** The whole laboratory dictionary for one language. */
export function labDictionary(language: SiteLanguage): LabDictionary {
  return language === 'zh-CN' ? ZH : EN;
}

/** One laboratory message, with its `{slot}`s filled. */
export function labCopy(language: SiteLanguage, key: LabKey, params?: CopyParams): string {
  const text: string = (labDictionary(language) as Record<string, string>)[key] ?? key;
  return interpolate(text, params);
}

/**
 * The laboratory lookup, bound to the shell's one language state.
 *
 * With no provider above it this is the English lookup, so a laboratory module
 * rendered on its own — a model test, a scene beside a fixture — keeps the words
 * it always printed.
 */
export function useLabCopy(): (key: LabKey, params?: CopyParams) => string {
  const { language } = useLanguage();
  return useCallback((key: LabKey, params?: CopyParams) => labCopy(language, key, params), [language]);
}

/** App-owned errors follow language changes; raw server diagnostics stay verbatim. */
export function useLabMessage() {
  const copy = useLabCopy();
  type Message = string | ((copy: ReturnType<typeof useLabCopy>) => string);
  const [stored, setStored] = useState<{value: Message}>({value: ''});
  const setMessage = useCallback((value: Message) => setStored({value}), []);
  return [typeof stored.value === 'function' ? stored.value(copy) : stored.value, setMessage] as const;
}
