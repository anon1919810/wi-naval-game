/**
 * The concept-design dictionary: the optional declared configuration, the
 * reviewed proposals it produces, and the adapted empirical screen it feeds.
 *
 * These strings are a helper dictionary rather than more rows in
 * `./workspace`. The concept screen is one feature with one owner, it is much
 * larger than any single editor in the workbench, and folding it into the
 * workspace dictionary would put a hundred concept words behind the same edit
 * as everything else on the page. Everything else about the discipline is the
 * same as `./workspace` and `./lab`: English is the source, Chinese is
 * shape-checked against it by the type system, keys are dotted and flat so a key
 * is greppable from the component that prints it, and interpolation is the same
 * `{slot}` rule.
 *
 * What is *not* routed through here, exactly as elsewhere: canonical unit
 * symbols, ledger item ids, system ids, the API's own enum values, request
 * fingerprints, and the core's diagnostic `code`s and `message` sentences. Those
 * are printed exactly as the core wrote them, and the words around them say what
 * kind of thing they are.
 */

