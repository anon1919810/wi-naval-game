/** One concept message in one language, with its `{slot}`s filled. */
export function conceptCopy(language: SiteLanguage, key: ConceptKey, params?: CopyParams): string {
  const dictionary: ConceptDictionary = language === 'zh-CN' ? ZH : EN;
  return interpolate((dictionary as Record<string, string>)[key] ?? key, params);
}

/**
 * The concept lookup bound to the shell's one language state.
 *
 * The returned function is stable while the language is, so switching language
 * re-renders the words and nothing else: no remount, no re-read, no reset draft.
 */
export function useConceptCopy(): (key: ConceptKey, params?: CopyParams) => string {
  const { language } = useLanguage();
  return useCallback((key: ConceptKey, params?: CopyParams) => conceptCopy(language, key, params),
    [language]);
}
