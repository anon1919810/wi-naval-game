/** One compatibility message in one language, with its `{slot}`s filled. */
export function sps3b3Copy(language: SiteLanguage, key: Sps3b3Key, params?: CopyParams): string {
  const dictionary: Sps3b3Dictionary = language === 'zh-CN' ? ZH : EN;
  return interpolate((dictionary as Record<string, string>)[key] ?? key, params);
}

/**
 * The compatibility lookup bound to the shell's one language state.
 *
 * The returned function is stable while the language is, so switching language
 * re-renders the words and nothing else.
 */
export function useSps3b3Copy(): (key: Sps3b3Key, params?: CopyParams) => string {
  const { language } = useLanguage();
  return useCallback((key: Sps3b3Key, params?: CopyParams) => sps3b3Copy(language, key, params),
    [language]);
}

/**
 * A field's label, preferring the curated bilingual name and falling back to
 * the catalogue's own English auto label.
 *
 * A dynamic `sps.field.<name>` lookup is intentionally not a total function over
 * the catalogue: the catalogue names 222 fields and only the reader-facing ones
 * are curated. An uncurated field keeps the name the core reported rather than a
 * guessed translation, which is the same rule `dataLabel` follows for metrics.
 */
export function sps3b3FieldLabel(
  copy: (key: Sps3b3Key, params?: CopyParams) => string,
  name: string,
  fallback: string,
): string {
  const key = `sps.field.${name}` as Sps3b3Key;
  const label = copy(key);
  return label === key ? fallback : label;
}
