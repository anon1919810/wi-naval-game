/**
 * The SpringSharp 3b3 compatibility dictionary.
 *
 * The compatibility screen is a feature of its own: seven source pages, their
 * native units, the driver/lock controls and the saved result. Keeping its words
 * here rather than in `./workspace` means the workbench dictionary is not opened
 * by every change this feature makes, which is the same discipline `./concept`
 * and `./lab` already follow. English is the source, Chinese is shape-checked
 * against it by the type system, keys are dotted and flat so a key is greppable
 * from the component that prints it, and interpolation is the shell's `{slot}`
 * rule.
 *
 * What is deliberately *not* routed through here: the source's own enum option
 * text and native units, ledger/system ids, and the core's diagnostic `code`s
 * and `message` sentences. Those are printed exactly as the core wrote them, in
 * the field's own unit, because inventing a friendlier name for a source value
 * would make a claim about the source this interface cannot make.
 */

